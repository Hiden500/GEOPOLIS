/**
 * ВПРЫСНУТЫЙ ПЕРЕВОДЧИК — для модуля, который сам хук вызвать не может.
 *
 * `useTranslation` доступен только компонентам. Чистая функция (адаптер модели
 * экрана) переводчиком не владеет и владеть не должна: она получает его
 * параметром — ровно так же, как уже получает `domainName` и `renderLine`.
 * Импортировать i18n она не может, иначе перестанет быть чистой и потянет за
 * собой словарь в каждый тест, который её вызывает.
 *
 * Namespace заявлен ТИПОМ, а не соглашением об имени переменной, по двум
 * причинам:
 *
 * 1. `__tests__/localeKeys.test.ts` узнаёт переводчик по объявлению. Для хука
 *    это `useTranslation("ns")` в том же файле, а у впрыснутого переводчика
 *    объявление и вызовы живут в РАЗНЫХ файлах — связать их может только
 *    аннотация рядом с вызовами. Без неё ключи впрыснутого переводчика
 *    оказались бы вне проверки «ключ, который просит код, есть в словаре», и
 *    первая же опечатка вышла бы к игроку сырым идентификатором.
 * 2. Подмену словаря ловит компилятор: `Namespace` попадает в тип поля, а типы
 *    необязательных полей обязаны быть совместимы, поэтому `Translator<"screen">`
 *    в слот `Translator<"adapter">` не проходит. Проверку держит
 *    `__tests__/translatorNamespace.test.ts`.
 *
 * Поля `__namespace` во время исполнения не существует — оно только носитель
 * параметра типа.
 */
export type Translator<Namespace extends string> = {
  (key: string, params?: Record<string, string | number>): string;
  readonly __namespace?: Namespace;
};
