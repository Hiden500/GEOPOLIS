/**
 * Вариативность характера (docs/AI_RULES.md §"Искусственный интеллект
 * стран") — Country.aiTraits сеется один раз в createGame() через seeded RNG
 * (shared/src/utils/rng.ts), диапазон ниже. Не читать напрямую как "истину" —
 * это дешёвая иллюзия индивидуальности, не реальная характеристика страны.
 */
export const AI_TRAIT_MIN = 0.6;
export const AI_TRAIT_MAX = 1.4;

/**
 * Перевод признака характера в множитель порога. Признак живёт в
 * [AI_TRAIT_MIN, AI_TRAIT_MAX] со средним 1, поэтому отклонение (trait − 1)
 * лежит в ±0,4, а `strength` задаёт, во сколько раз это отклонение доходит до
 * конкретного порога. Нейтральный характер (`trait === 1`) даёт РОВНО 1 при
 * любой силе — то есть страна с плейсхолдером `createCountry()` `{1, 1}` и все
 * существующие фикстуры ведут себя ровно как до появления характеров.
 *
 * Функция здесь, а не у каждого потребителя: смысл «характер сдвигает порог»
 * должен иметь одно место, где его можно поменять, иначе сдвиги разойдутся —
 * ровно тем способом, которым разошлась база бюджетной росписи
 * (server/src/simulation/economy/budgetBase.ts).
 */
export function traitScale(trait: number, strength: number): number {
  return 1 + (trait - 1) * strength;
}

/**
 * Сила `riskTolerance` у порога аустерити (Правило A): порог долг/ВВП, с
 * которого страна начинает резать расходы, равен
 * `DEBT_GDP_PENALTY_THRESHOLD × traitScale(riskTolerance, …)`.
 *
 * 0,5 даёт коридор порогов 0,48…0,72 вокруг общих 0,6, и обе границы выбраны
 * замером живого 1946 (120 месяцев, 157 стран, прогон 2026-08-09): пиковая
 * долговая нагрузка мира распределена обрывом — семь стран в 0,655…0,729,
 * затем 0,496, 0,445 и всё остальное ниже 0,4. Верхняя граница 0,72 лежит
 * ВНУТРИ этого пика, то есть самая рисковая страна всё-таки начинает резать, а
 * не проваливается мимо порога навсегда; нижняя 0,48 захватывает страну с
 * пиком 0,496, которой общий порог 0,6 не касался. Шире коридор делать нечем:
 * за 0,78 в мире нет никого, и множитель просто перестал бы что-либо значить.
 *
 * ЦЕНА РИСКА НЕ БЕСПЛАТНА, и это главное в выборе точки приложения. Штраф
 * росту ВВП начинается с `DEBT_GDP_PENALTY_THRESHOLD` независимо от характера
 * (`EconomyTick.ts`), поэтому терпимая к риску страна оттягивает затягивание
 * пояса и платит за это ростом — а не получает более мягкое правило даром.
 */
export const AI_TRAIT_DEBT_TOLERANCE = 0.5;

/**
 * Сила `aggressiveness` у порога кризиса Правила C: страна снимает деньги с
 * армии в пользу социалки не при общем `STABILITY_LOW`, а при
 * `STABILITY_LOW / traitScale(aggressiveness, …)` — агрессивная терпит больше
 * беспорядка, прежде чем тронуть военный бюджет, осторожная перекладывает
 * раньше. Деление, а не умножение: БОЛЬШЕ агрессивности — НИЖЕ порог.
 *
 * ПОЧЕМУ ПОРОГ, А НЕ ВЕЛИЧИНА СДВИГА. Сдвиг Правила C ограничен потолком
 * welfare и полом military, а стартовые доли в 1946 не одни на всех — их три
 * набора по `economyProfile` (welfare 0,22/0,12/0,30 при military
 * 0,20/0,30/0,15). У первого набора упирается потолок welfare, у второго — пол
 * military, у третьего сдвига нет вовсе. Множитель на любую ОДНУ из этих
 * границ жив у одного профиля и мёртв у другого; множитель на порог входа не
 * зависит от профиля вообще.
 *
 * ВЕЛИЧИНУ ВЫБРАЛ ЗАМЕР, а не вкус (`server/scripts/probeAiTraits.ts`, сид
 * 20260809, 120 месяцев живого 1946, 157 стран). Скрипт гоняет ДВА мира на
 * одном сиде — с характерами и с зажатыми в 1.0 — и считает, у скольких стран
 * исход разошёлся:
 *
 * ```text
 *  сила   коридор порогов   исход разошёлся   доля military иная   избежали C
 *  0,25   36,4…44,4                     12                     6            0
 *  0,50   33,3…50,0                     29                    22            2
 *  0,75   30,8…57,1                     43                    34            9
 * ```
 *
 * Взято 0,5 — НАИМЕНЬШЕЕ из измеренных, при котором живы ОБЕ стороны признака.
 * При 0,25 колонка «избежали C» пуста: агрессивная половина характера не
 * спасает от кризиса ни одну страну, то есть работает только осторожная — а
 * односторонний признак ничем не лучше мёртвого. При 0,75 разброс больше, но
 * коридор доходит до 57,1, и «низкой стабильностью» пришлось бы называть
 * вполне устойчивую страну — это уже не сдвиг порога характером, а другой
 * порог. 0,5 держит коридор внутри читаемого смысла `STABILITY_LOW`.
 *
 * Направление проверено тем же прогоном и на 0,5 верное: страны, избежавшие
 * Правила C благодаря характеру, имеют среднюю агрессивность 1,31 (выше
 * нейтральной), попавшие под него из-за характера — 0,77 (ниже).
 *
 * Верхнюю границу коридора держит гистерезис: порог возврата у той же страны
 * считается как «её порог кризиса + зазор», поэтому кризисный порог структурно
 * не может обогнать порог возврата ни при каком характере (см.
 * STABILITY_RECOVERED).
 */
export const AI_TRAIT_UNREST_TOLERANCE = 0.5;
