import { DEBT_GDP_PENALTY_THRESHOLD } from "./economy";

/** −5% дискреционных расходов за тик при дефиците (Правило A). */
export const AUSTERITY_CUT = 0.95;

/**
 * +5% дискреционных долей за тик при восстановлении (обратный ход Правила A,
 * 2026-08-02). Скорость симметрична урезанию: спад и восстановление — одна
 * реакция с разным знаком, и несимметричная скорость потребовала бы отдельного
 * обоснования, которого нет. Потолок восстановления — стартовая доля
 * (= spendingFloor × 2), поэтому обратный ход отменяет ровно урезание
 * аустерити и не спорит с Правилами B/C, поднимающими доли выше старта.
 */
export const AUSTERITY_RESTORE = 1.05;

/**
 * Гистерезис обратного хода Правила A, ось 1 — МИНИМАЛЬНЫЙ ЗАПАС ПРОФИЦИТА в
 * долях дохода: восстановление идёт только при budgetBalance ≥ margin × income.
 *
 * Эта ось отвечает за отсутствие осцилляции cut/restore. Наблюдаемый цикл
 * устроен так: восстановление возвращает структурный дефицит, дефицит
 * наращивает долг за порог, аустерити возвращает профицит, профицит гасит
 * долг под порог — и заново. Запас профицита убирает причину: пока запас
 * больше добавки расходов от шага восстановления, сам шаг не способен
 * перевести бюджет в дефицит — восстановление останавливается ДО черты, а не
 * перепрыгивает её.
 *
 * Ширина 0,03 снята замером (server/scripts/probeAusterityRecovery.ts,
 * 156 стран, 24 мес принудительного дефицита + восстановление до 360-го
 * месяца, структурный дефицит --bias 0.2): margin 0 — осцилляция cut/restore
 * у 152 стран, до 89 смен направления доли education; 0,01 — у 95 стран, до
 * 29 смен; 0,02 — ещё протекает (7 стран, до 5 смен); 0,03 — 0 стран, максимум
 * 2 смены (спад → подъём) даже при --bias 0.3. Цену ширины мерил тот же
 * прогон: здоровый сценарий (--bias 0) при финальных константах возвращает к
 * стартовым долям все 83 урезанные страны (медиана 34 мес после стресса),
 * т.е. запас не запирает восстановление, а только останавливает его у черты
 * дефицита.
 * Верхняя граница шага — (AUSTERITY_RESTORE − 1) × Σ дискреционных долей
 * (в данных 1946 Σ = 0,85 у всех — до 0,0425 дохода), но в зоне равновесия
 * реальный шаг меньше (доли упираются в потолки), поэтому ширину решает
 * замер, а не эта грубая оценка.
 */
export const AUSTERITY_RECOVERY_SURPLUS_MARGIN = 0.03;

/**
 * Гистерезис обратного хода Правила A, ось 2 — потолок долга/ВВП, ниже
 * которого восстановление разрешено. Урезание начинается при долге выше
 * DEBT_GDP_PENALTY_THRESHOLD (0,6), восстановление — только когда долг
 * погашен до четверти этого порога.
 *
 * Эта ось отвечает не за осцилляцию (её закрывает запас профицита выше), а за
 * СКОРОСТЬ РАСЧИСТКИ ДОЛГОВ: страна, начавшая тратить как раньше при ещё
 * заметном долге, гасит его в разы дольше, и переходная долговая яма первых
 * лет перестаёт рассасываться (свойство мира — exportIncome.test.ts). Разовый
 * замер живого 1946 (2026-08-02, чекпойнт — 60-й месяц; числа также в
 * docs/DECISIONS.md): потолок 0,6 оставлял в долгу 34% мира, 0,3 — 16%, 0,2 — 8%
 * (впритык к порогу теста 10%), 0,15 — 6% при полной расчистке к 120-му
 * месяцу у всех вариантов. Взято 0,15: единственное из измеренных значений с
 * запасом к порогу, а не на его краю; цена — восстановление стартует на
 * несколько месяцев позже, что на полном цикле probeAusterityRecovery
 * не запирает ни одну страну.
 */
export const AUSTERITY_RECOVERY_DEBT_CEILING = DEBT_GDP_PENALTY_THRESHOLD / 4;

/** Порог доминирования игрока (calculateBaseInfluence), ~×2.5 (Правило B). */
export const THREAT_LEVEL = 50;

/** +5% military за тик у угрожаемых соперников (Правило B). */
export const MILITARY_RAMP = 1.05;

/** Потолок military как доля дохода (Правило B). */
export const MILITARY_CAP_SHARE = 0.4;

/** +отношение/тик между со-угрожаемыми соперниками (Правило B). */
export const COALITION_STEP = 5;

/** Скорость роста влияния игрока — бандвагонинг (Правило B). */
export const INFLUENCE_GRAVITY = 0.1;

/** Порог "низкой" stability для Правила C. */
export const STABILITY_LOW = 40;

/**
 * Порог «кризис позади» для Правила C: выше него доля military возвращается к
 * стартовой. Задан ОТ `STABILITY_LOW`, а не отдельным числом: порог возврата
 * ниже порога кризиса означал бы правило, которое одновременно снимает и
 * возвращает долю, и такую опечатку структура не даёт сделать.
 *
 * Зазор — это гистерезис: в зоне 40…45 не двигают ни туда, ни обратно, чтобы
 * страна с равновесием у самой черты не перекладывала бюджет каждый месяц.
 * Ширину выбрал замер (`server/scripts/probeStabilityRule.ts`, 120 месяцев живого
 * 1946): из 82 стран, у которых доля military просела ниже стартовой, черту 45
 * к десятому году перешагнули 17, черту 50 — только 6. Зазор в 10 пунктов
 * оставил бы страну с равновесием 47 на кризисном бюджете навсегда — а её
 * кризис давно кончился.
 *
 * С 2026-08-09 оба порога ИНДИВИДУАЛЬНЫ (`aggressiveness`, см.
 * AI_TRAIT_UNREST_TOLERANCE), и зазор пережил это без изменений: у страны
 * порог возврата считается как её собственный порог кризиса плюс ЭТОТ зазор
 * (`STABILITY_RECOVERED − STABILITY_LOW`), а не как общее число 45. Иначе
 * агрессивная страна с порогом кризиса 36,4 получила бы зону гистерезиса
 * шириной 8,6 вместо 5, а осторожная с порогом 44,4 — 0,6, и одна и та же
 * механика вела бы себя у разных стран по-разному без всякого замысла.
 */
export const STABILITY_RECOVERED = STABILITY_LOW + 5;

/**
 * Доля дохода, переводимая military→welfare за тик (Правило C) — и та же
 * скорость обратного возврата welfare→military при восстановлении.
 */
export const WELFARE_SHIFT_RATE = 0.02;

/** Потолок welfare как доля дохода (Правило C). */
export const WELFARE_CAP_SHARE = 0.3;

