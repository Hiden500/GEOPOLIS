/**
 * Сколько ПОДРОБНЫХ диагностических фактов об отказах примитивов хранится
 * одновременно ДЛЯ ОДНОГО ИСТОЧНИКА (`GameState.pendingWorldFacts`,
 * `kind: "primitive_rejected"`, поле `source`). Сверх капа копится не текст, а
 * один агрегат «хвост есть» — тот же приём, что `renderHiddenCrises` для
 * кризисов, и свой у каждого источника.
 *
 * Кап нужен потому, что эти факты вычищаются только генерацией промта, а
 * пишутся на КАЖДЫЙ отказ: движок зовётся на каждый клик игрока и на каждый
 * ответ модели, и между двумя промтами их может накопиться сколько угодно.
 * Растёт при этом и промт, и сейв.
 *
 * Значение выведено, а не выбрано: столько отказов может дать один полный
 * законный ход (`MAX_SOFT_PRIMITIVES_PER_TURN + MAX_STRUCTURAL_PRIMITIVES_PER_TURN`),
 * если движок отклонит в нём всё до последнего примитива. Ниже — и законная
 * попытка выжать ход целиком теряла бы часть диагностики; выше — и хранилось бы
 * то, что по построению может быть только повторными попытками, а модели и
 * игроку про них хватает одной строки.
 *
 * **Почему кап ПО ИСТОЧНИКУ, а не общий** (2026-07-26, внешний аудит). Каналов
 * два (игрок и режиссёр), они независимы, и общая куча делала диагностику
 * вытесняемым ресурсом: одиннадцать заведомо отклоняемых кликов, отданных до
 * обработки ответа модели, занимали все подробные слоты, и точная причина отказа
 * примитива МОДЕЛИ заменялась агрегатом. Модель после этого не знает, какой её
 * глагол или предпосылка неверны, — то есть повторяет ту же попытку, ровно
 * против чего диагностика и заведена (docs/PRIMITIVES.md §3).
 *
 * Цена разделения — верхняя граница секции удваивается (2 × кап + 2 агрегата).
 * Она приемлема потому, что кап держит ЧИСЛО записей, а фактический размер
 * секции при обоих переполненных каналах запинен тестом.
 *
 * **Чего этот кап НЕ держит, названо прямо** (уточнено 2026-07-27 по
 * независимому ревью; прежняя формулировка ссылалась на `MAX_PRIMITIVE_ID_LENGTH`
 * как на вторую границу и обещала больше, чем та даёт).
 * `MAX_PRIMITIVE_ID_LENGTH` ограничивает длину ЗНАЧЕНИЯ трёх известных
 * идентификаторов — и только их. Длину ОДНОЙ диагностической записи он не
 * ограничивает: `.strict()` в схеме глагола кладёт в причину ИМЯ нераспознанного
 * ключа целиком, а имена ключей в теле запроса ничем не ограничены. Число
 * записей × неограниченная длина = неограниченная секция; закрывается капом на
 * длину самой записи (`docs/TODO.md`).
 */
export const MAX_PENDING_REJECTION_FACTS_PER_SOURCE =
  MAX_SOFT_PRIMITIVES_PER_TURN + MAX_STRUCTURAL_PRIMITIVES_PER_TURN;
