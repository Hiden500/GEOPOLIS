// --- капы примитивов на игровой ход (docs/PRIMITIVES.md §4) ---
//
// Все четыре капа ниже считаются НА ИГРОВОЙ ХОД (месяц), а не на вызов движка.
// Счётчики живут в `GameState.primitiveTurnBudget` и обнуляются со сменой даты.
// Ответ модели и приказ игрока тратят ОДИН бюджет: разделить их значило бы
// оставить обход коридора магнитуды частотой, только через другой канал.

/** Максимум мягких примитивов за игровой ход (все каналы вместе). */
