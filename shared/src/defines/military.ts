/**
 * Сколько единиц militarySpending приходится на 1 единицу сырьевого спроса
 * производства: demand = militarySpending / EQUIPMENT_RESOURCE_DEMAND_SCALE.
 *
 * КАЛИБРОВКА — по живым данным 1946 (probeResourceGates, раздел 4), а не по
 * фикстуре. Требование пользователя: у типичной страны в мирном 1946-м
 * покрытие ≥ 1 — гейт не душит мир по умолчанию, он наказывает блокаду,
 * войну и потерю добычи. При 20 000 спрос СССР ≈ 378 тыс. ед./мес против
 * ~7,9 млн запаса военного сырья + ~370 тыс. добычи; устойчивость держит
 * импорт дефицита (TradeTick, IMPORT_RATE × нехватка до резерва): страна
 * без собственных месторождений покрывает спрос покупкой, пока
 * demand ≲ extraction + IMPORT_RATE × резерв набора. Медианное покрытие и
 * долю стран < 1 на длинном прогоне печатает probeResourceGates.
 */
export const EQUIPMENT_RESOURCE_DEMAND_SCALE = 20_000;

