/**
 * СТАРТОВЫЙ МОБИЛИЗАЦИОННЫЙ ПУЛ — доля населения страны на начало партии
 * (введён 2026-07-31).
 *
 * ЗАЧЕМ. Сценарий 1946 не размечает `military` вовсе: схема поля допускает
 * (`scenario1946Schemas.ts`), но ни один файл данных их не содержит, поэтому
 * все 157 стран начинали январь 1946 года — через полгода после мировой войны —
 * с АРМИЕЙ РОВНО НОЛЬ. Пул набирался по 0,1% населения в месяц с нуля.
 *
 * Следствие было не косметическим, а разрушительным для всей военной механики:
 * `sideStrength` обеих сторон в первые месяцы ≈ 0, поэтому исход решала
 * случайная разница в тысячу человек, отношение сил уходило в бесконечность и
 * забирало весь фронт разом. Замер (`server/scripts/probeWarFeedback.ts`):
 * Румыния против Югославии — равные соседи — теряла все 6 регионов за 6
 * месяцев, причём на первом месяце у атакующего было 0 манпауэра против 4283 у
 * обороны. Никакая правка формулы флипа этого не лечит: сравнивать нечего.
 *
 * КАЛИБРОВКА — от исторического порядка И от масштаба потерь. 15% населения в
 * мобилизационном пуле, `ACTIVE_PERSONNEL_SHARE` от него в строю: 1,5%
 * населения под ружьём. Румыния получает ~237 тыс., СССР — ~2,5 млн; в январе
 * 1946 это верный порядок (демобилизация ещё шла, счёт был на миллионы).
 *
 * Первая попытка — 2% пула, то есть 0,2% населения — провалилась по ВТОРОЙ
 * причине, и она важнее исторической: `WAR_CASUALTY_BASE_PER_FRONT_REGION`
 * задаёт потери абсолютным числом на участок фронта, независимо от размера
 * армии (так и задумано, см. комментарий у константы). При армии в 31 тыс. и
 * потерях 20 тыс./мес она исчезала за полтора месяца — и война возвращалась к
 * состоянию «нули против нулей», от которого мы её и лечили. Стартовая армия
 * обязана быть соразмерна интенсивности боёв, иначе любая война кончается
 * взаимным обнулением, а не исходом.
 *
 * Точные исторические штаты по 157 странам — разметка данных с провенансом,
 * отдельная работа (`docs/IDEAS.md`). Схема сценария поле уже допускает, и
 * `seedStartingArmies` уважает его, если оно появится.
 */
export const STARTING_MANPOWER_POPULATION_SHARE = 0.15;

