// --------------------------------------------------------------------------
//
// ЗАЧЕМ ПОЯВИЛСЯ (решение пользователя 2026-08-08, вариант «формальная связь
// держит присутствие»). До него затухание было БЕЗУСЛОВНЫМ и с капом, то есть
// линейным у малых величин, — оно доводило любую связь до РОВНОГО НУЛЯ за
// конечное число месяцев. Замер 240 месяцев живого 1946
// (`server/scripts/probeIntercountryAi.ts`, 2026-08-08) показал масштаб: сумма
// влияния мира 14 050 → 496, связей 300 → 189, сфер влияния 114 → 6. Мир не
// просто не наживал новых связей — он терял авторские, и вместе с ними исчезал
// вход всякого механизма, ключом которого служит присутствие.
//
// ПОЧЕМУ ПОЛ ЗАДАЁТ ИМЕННО ОБЯЗАТЕЛЬСТВО. Связи бывают двух происхождений:
// созданные ХОДОМ (вассалитет, гарантия, союз — примитивы алфавита) и
// ВЫВЕДЕННЫЕ движком (сфера влияния — следствие того, что влияние перевалило
