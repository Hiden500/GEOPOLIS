/**
 * Дрейф отношений к структурному тяготению пары — доля остаточного разрыва за
 * тик (тик = один игровой месяц, `SimulationEngine.ts`).
 *
 * До 2026-07-28 это называлось «затухание к нейтральности» и тянуло отношения
 * к нулю. Целью дрейф обзавёлся вместе с идеологическим модификатором: ноль
 * был неявной целью «мир без свойств», а теперь цель выводится из состояния
 * пары (`server/src/simulation/diplomacy/affinity.ts`). Дело, сделанное
 * примитивом, по-прежнему выдыхается — но выдыхается К СТРУКТУРЕ, а не в
 * безразличие: соседи с чужим режимом возвращаются к взаимной прохладе, а не
 * к нулю.
 */
export const RELATION_DRIFT_RATE = 0.03;
/** Потолок сдвига отношений дрейфом за один тик, пункты шкалы. */
export const RELATION_DRIFT_CAP = 2;
/**
 * Порог материализации записи об отношениях, пункты шкалы.
 *
 * Пара заводит запись в `relations` только когда её тяготение или текущее
 * значение по модулю не меньше этого; иначе запись удаляется как шум. Без
 * порога каждая пара с общей границей и близкой к нулю целью навсегда
 * поселилась бы в сейве числом вида 0.0007.
 */
export const RELATION_MATERIALIZE_MIN = 1;

/** Естественное затухание влияния — доля/тик. */
export const INFLUENCE_DECAY_RATE = 0.02;
/**
 * Потолок величины затухания влияния за один тик.
 *
 * Затухание безусловным быть перестало: ниже пола, который держит взятое ходом
 * обязательство, оно связь не опускает — см. `PRESENCE_FLOOR_COMMITMENT` в
 * конце файла (там же, где стоят его анкеры).
 */
export const INFLUENCE_DECAY_CAP = 0.5;

/**
 * Отношения ниже — страна автоматически становится соперником.
 *
 * ЧИСЛО СМЕНИЛОСЬ 2026-07-31 (было −70, аудит формул `.agent/audits/
 * formula-audit-2026-07-30.md`). −70 брался с НОМИНАЛЬНОЙ шкалы отношений
 * [−100, +100], а вход перехода живёт на другой: цель дрейфа —
 * `structuralAffinity`, у которой ровно один знакопеременный член (идеология,
 * ±`IDEOLOGY_AFFINITY_SPAN/2` при полном контакте), а общий враг и зависимость
 * НЕОТРИЦАТЕЛЬНЫ. Ниже −20 без идущей войны формула не опускается по
 * построению, то есть порог был недостижим, соперников не возникало никогда, и
 * вместе с ними — общего врага, единственного входа в союз.
 *
 * Живой замер (`createGame("1946")`, 433 кандидатных пары, 2026-07-31) строже
 * теоретической границы: максимальная идеологическая дистанция в поставляемых
 * данных 0,778, а не 1, поэтому фактический пол тяготения −11,12, а не −20.
 * Предложенные аудитом −15…−18 остались бы такими же мёртвыми числами.
 *
 * −2,5 выбрано по РАСПРЕДЕЛЕНИЮ живого мира, а не по краю шкалы: медиана
 * тяготения +17,8, 5-й процентиль +2,3, 1-й процентиль −3,1. Порог отделяет
 * нижние ~2% пар от остального мира и держит запас в обе стороны — 8,6 пункта
 * до фактического пола (крест дрейфа за конечное число тиков) и 2,5× до порога
 * материализации записи (`RELATION_MATERIALIZE_MIN`), ниже которого отношение
 * считается шумом. Оба запаса проверяются на живых данных в
 * `server/src/simulation/diplomacy/thresholdReach.test.ts`, а не на глаз.
 *
 * ЦЕНА РЕШЕНИЯ, названная прямо. Прежний порог был настолько глубок, что пара
 * БЕЗ канала связи (её тяготение ограничено `IDEOLOGY_AFFINITY_SPAN/2 ×
 * CONTACTLESS_IDEOLOGY_SALIENCE` = 10 по модулю) не могла его пересечь
 * арифметически, и на этом стояло право тика не обходить все 12 246 пар мира.
 * Теперь гарантия «пропущенная пара не пересечёт порог» держится только для
 * порога СОЮЗА. Для соперничества она заменена продуктовым правилом: соперник —
 * это отношение, а не рейтинг несходства; двое без общей границы, без влияния и
 * без единой формальной связи — не соперники, а посторонние. Идеология для них
 * и так вдвое менее весома (`CONTACTLESS_IDEOLOGY_SALIENCE`). Поведение тика от
 * этого не меняется — меняется обоснование, и оно записано здесь, а не
 * подразумевается.
 */
export const RIVAL_RELATION_THRESHOLD = -2.5;
/**
 * ПИВОТ порога согласия на союз: значение для пары, стоящей ровно в точке
 * идеологического безразличия и не имеющей общего врага. Сам порог считается
 * от пары (`allianceThreshold`), общим для всех он перестал быть 2026-07-28.
 */
export const ALLY_RELATION_THRESHOLD = 70;
/**
 * Отношения выше — страна автоматически покидает список соперников.
 *
 * Опущен вместе с порогом соперничества (было −30) и по тем же замерам. Два
 * условия, оба под тестом:
 *
 *  1. Строго ВЫШЕ `RIVAL_RELATION_THRESHOLD` — гистерезис, иначе пара входила
 *     бы в соперничество и выходила из него в одном проходе тика.
 *  2. По модулю строго БОЛЬШЕ `RELATION_MATERIALIZE_MIN`. Условие неочевидное и
 *     стоит того, чтобы быть названным: примирение проверяется обходом
 *     `relations`, а запись оттуда удаляется, когда И значение, И цель по модулю
 *     меньше порога материализации. Порог примирения внутри полосы шума означал
 *     бы, что запись успевает исчезнуть раньше, чем условие выхода выполнится, —
 *     и соперничество замерзало бы навсегда без единого способа его снять.
 */
export const RIVAL_RECONCILE_THRESHOLD = -1.5;

/**
 * Сдвиг отношений при АВТОМАТИЧЕСКОМ входе в соперничество, пункты шкалы.
 *
 * ЧИСЛО СМЕНИЛОСЬ 2026-07-31, вторым шагом после порогов: было −40, зашитое
 * литералом в `DiplomacyService.addRival`. Пороги опустили с −70 на −2,5, сдвиг
 * не тронули — пара пересекала порог на −2,6 и одним шагом улетала на −60
 * (сдвиг применяется дважды: каждая сторона заводит соперника сама, а
 * `changeRelation` кладёт половину встречной стороне, итог 1,5 × сдвиг у обеих).
 * Это вшестеро глубже ФАКТИЧЕСКОГО пола структурного тяготения на данных 1946
 * (−11,12), и дрейф вытягивал пару обратно годами: период полураспада разрыва
 * ln2 / `RELATION_DRIFT_RATE` ≈ 23 месяца.
 *
 * ГЛАВНЫЙ ДОВОД — НЕ МАСШТАБ, А НАПРАВЛЕНИЕ СВЯЗИ. `addRival` вызывается ровно
 * из одного места (`DiplomacyTick`) и только как ВЫВОД состояния из отношений:
 * отдельного глагола «объявить соперничество» в алфавите примитивов нет
 * (`docs/PRIMITIVES.md` §2), то есть платить сдвигом некому и не за что.
 * Выведенный ярлык, двигающий собственный вход, — положительная обратная связь:
 * провал на 0,1 пункта ниже порога превращался в шестидесятипунктовый обвал, и
 * порог переставал что-либо значить.
 *
 * ЗАМЕР, ЗАДАВШИЙ ГРАНИЦЫ (`npx tsx scripts/probeDiplomacy.ts`, 120 месяцев на
 * `createGame("1946")`): 18 пар вошли в соперничество, НИ ОДНА не вышла. При
 * этом у всех 18 структурное тяготение (−11,12…−3,11) лежит НИЖЕ порога
 * примирения −1,5 — их равновесие под условием выхода, поэтому одним только
 * размером сдвига обратимость не чинится (и не должна: пока структура
 * враждебна, соперничество обязано держаться). Сдвиг отвечает за другое — за
 * пары, которых в соперничество загнало СОБЫТИЕ при невраждебной структуре.
 *
 * −4 выбрано между двумя измеренными границами, а не на глаз:
 *
 *  - сверху: 1,5 × сдвиг = 6 < 8,62 — расстояния от порога входа (−2,5) до
 *    живого пола тяготения (−11,12). Выведенный ярлык не имеет права уносить
 *    пару глубже, чем способна утянуть самая враждебная структура мира;
 *  - снизу: 1,5 × сдвиг = 6 — вшестеро шире полосы гистерезиса
 *    (`RIVAL_RELATION_THRESHOLD` … `RIVAL_RECONCILE_THRESHOLD` = 1 пункт),
 *    поэтому соперничество не мигает: минимальный эпизод у пары с медианным
 *    тяготением — около года, а не один тик.
 *
 * Обе границы и обратимость проверяются на живых данных в
 * `server/src/simulation/diplomacy/rivalryReversibility.test.ts`.
 */
export const RIVAL_ENTRY_RELATION_SHIFT = -4;

