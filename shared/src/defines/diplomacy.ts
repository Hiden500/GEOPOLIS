// --------------------------------------------------------------------------
// Идеология как модификатор союзов (docs/DECISIONS.md, 2026-07-27/28)
// --------------------------------------------------------------------------
//
// До 2026-07-28 идеология была БУЛЕВЫМ ГЕЙТОМ: `areIdeologicallyCompatible`
// искала в тексте ярлыка шесть подстрок, и несовпадение делало союз невозможным
// при любых отношениях. Два дефекта разного веса. Инженерный: решение
// принималось по человекочитаемой наклейке, поэтому после перевода ярлыка на
// вывод из координат права на союз лишились 103 страны из 157 вместо прежних 8.
// Продуктовый и главный: бинарность неверна по существу — в 1946 СССР и США
// только что вышли из союза, будучи антиподами, а Британия союзничала с СССР.
// Идеология делала союз дороже и недолговечнее, но не невозможным.
//
// Числа ниже подобраны так, чтобы выполнялись ЧЕТЫРЕ ИНВАРИАНТА, а не «на
// глаз». Каждый проверяется на самих константах в
// `server/src/simulation/diplomacy/__tests__/affinity.test.ts`:
//
//   1. `allianceThreshold` НИКОГДА не достигает `RELATION_SCALE_MAX` — союз
//      физически возможен для любой пары. Это и есть закрытие дефекта 103
//      стран: запрета больше нет ни в какой форме.
//   2. `allianceThreshold > allianceBreakThreshold` при любых входах — иначе
//      тик создавал бы союз, который сам же снимает в том же проходе.
//   3. Максимум тяготения БЕЗ общего врага строго меньше минимума порога без
//      общего врага — мир не сваливается в блоки на первом же тике.
//   4. Тяготение антиподов ПРИ полном общем враге выше их порога, а без врага
//      ниже их порога распада — союз антиподов возможен и непрочен.

