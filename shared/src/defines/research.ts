/**
 * Сколько единиц researchSpending дают 1 единицу прогресса домена при полной
 * (share=1) отдаче на тире 0 — тюнингуемая константа, как THREAT_LEVEL и
 * т.п. Подобрана так, чтобы полностью сфокусированная крупная держава
 * проходила тир примерно за 8-10 месяцев на старте партии.
 */
export const RESEARCH_SPENDING_SCALE = 2_000_000_000;

/** Замедление на каждый следующий тир — поздние прорывы непропорционально труднее ранних (docs/DECISIONS.md, 2026-07-06). */
export const TIER_SLOWDOWN_PER_TIER = 0.3;

/** Регионы с development выше этого порога считаются исследовательскими центрами. */
export const RESEARCH_CENTER_DEVELOPMENT_THRESHOLD = 0.7;
/** Бонус к прогрессу на каждый исследовательский центр страны. */
export const RESEARCH_CENTER_BONUS_RATE = 0.1;
/** Множитель бонуса от доли educationSpending/gdp. */
export const RESEARCH_EDUCATION_BONUS_MULTIPLIER = 2;

// --- фокус исследований: потолок доли и коридор сдвига ---
//
// Три первые константы переехали сюда из `llmActionCaps.ts` вместе с самим
// воздействием (2026-08-02): файл описывал пределы старого канала `actions`,
// которого больше нет, а потолок доли — свойство ИССЛЕДОВАНИЙ и живёт рядом с
// остальным их балансом. Значения не менялись: перевод глагола в алфавит не
// должен оказаться ещё и тихой рекалибровкой.

/**
 * Потолок доли researchSpending на один домен (docs/DECISIONS.md, 2026-07-06) —
 * остаток делят поровну домены без явной доли (ResearchTick.ts). Не 1.0:
 * сфокусированность не бесплатна, остальные направления всё равно получают
 * что-то. Это потолок МИРНОГО времени — см. `WAR_RESEARCH_SHARE_PENALTY`.
 */
export const MAX_RESEARCH_SHARE = 0.7;

/**
 * Admin capacity (независимый гейм-дизайн разбор, 2026-07-06): правительство,
 * воюющее на нескольких фронтах, отвлечено — потолок доли снижается на эту
 * величину за каждую активную войну страны (не только начатую ею: оборона
 * отвлекает так же). Применяется ко всем странам, включая игрока.
 *
 * С 2026-08-02 поправку считает КОРИДОР примитива `research_shift`, а не
 * валидатор старого канала: раньше она отклоняла присланную моделью долю, теперь
 * задаёт верхнюю границу того, что движок вправе выставить сам.
 */
export const WAR_RESEARCH_SHARE_PENALTY = 0.1;

/** Пол потолка — даже страна на нескольких фронтах не теряет фокус целиком. */
export const MIN_RESEARCH_SHARE_CAP = 0.3;

/**
 * Нижняя граница коридора сдвига фокуса за один примитив.
 *
 * Верхняя граница — сам потолок доли: `severe` в мире, где домен пуст, а страна
 * не воюет, доводит фокус ровно до `MAX_RESEARCH_SHARE` одним ходом. Это и есть
 * перенос возможностей старого канала без потерь: он позволял выставить
 * предельную долю сразу, и алфавит обязан оставлять то же достижимым — разница
 * лишь в том, что число теперь считает движок из остатка, а не присылает модель.
 *
 * Коридор схлопывается в этот минимум, когда двигать некуда: домен уже на
 * потолке (для `toward`) или уже на нуле (для `away`).
 */
export const RESEARCH_FOCUS_SHIFT_MIN = 0.05;
