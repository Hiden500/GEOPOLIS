/**
 * Потери войны (docs/plans/08_WAR_WAVE1.md, Шаг 3) — тюнингуемый плейсхолдер,
 * не финальная калибровка. Базовая месячная «интенсивность» одного
 * контактного (фронтового) региона: сколько человек уносит война на этом
 * участке за месяц. Общий помесячный урон = база × (число фронтовых регионов
 * обеих сторон), распределяется между сторонами по доле силы ПРОТИВНИКА
 * (слабейшая сторона теряет больше — facing a stronger enemy).
 *
 * Нюанс баланса: интенсивность привязана к участку фронта, НЕ пропорциональна
 * размеру армии. Поэтому маленькая армия быстро исчерпывается и потери
 * «переливаются» в гражданское население (Region.population) — тематически
 * это разгром малой армии с мобилизацией/жертвами среди гражданских, а не
 * баг. 10 000/мес на регион при типичном фронте в 2 региона даёт ~120 000/год
 * на страну — исторически правдоподобный порядок для крупной державы 1946.
 */
export const WAR_CASUALTY_BASE_PER_FRONT_REGION = 10_000;

/**
 * warScore (docs/plans/08_WAR_WAVE1.md, Шаг 2a) — детерминированная оценка
 * «насколько решительно ведёт лидирующая сторона», −100..100 от лица
 * атакующих (+ = атакующие впереди). Тюнингуемые плейсхолдеры.
 *
 * Территориальная компонента: каждый нетто-флип оккупации (toAttackers −
 * toDefenders) даёт столько очков. ~7 чистых флипов = решительные 100.
 */
export const WARSCORE_PER_NET_FLIP = 15;

/**
 * Компонента потерь: относительное доминирование по потерям
 * (defenderCas − attackerCas)/(сумма) ∈ [−1,1], умноженное на этот вес.
 * Кто пролил меньше крови относительно врага — в плюсе. Максимум ±40 очков
 * от одних потерь, территория может добить до ±100 (итог капается).
 *
 * Нюанс баланса / отклонение от буквы плана: план называл третьим входом
 * «длительность (истощение тянет к миру)». warScore здесь — измеритель
 * ПРЕИМУЩЕСТВА (кто побеждает), а не готовности к миру; истощение от
 * длительности уже отыгрывается отдельной военной усталостью в
 * WarService.makePeace (STALEMATE_WEARINESS_*), не смешивается с сигналом
 * преимущества, иначе решительная, но долгая победа занижалась бы неверно.
 */
export const WARSCORE_CASUALTY_WEIGHT = 40;

/**
 * Пороги ярлыка исхода для промта LLM (warScoreLabel): |score| ≥
 * DECISIVE → «решительно побеждает», ≥ WINNING → «побеждает», иначе
 * «примерно равно». Тюнингуемые плейсхолдеры — грубая шкала, чтобы модель
 * предлагала соразмерный мир.
 */
export const WARSCORE_DECISIVE_THRESHOLD = 60;
export const WARSCORE_WINNING_THRESHOLD = 20;
