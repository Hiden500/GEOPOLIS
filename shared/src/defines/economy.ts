/**
 * НАКОПЛЕНИЕ ИНФРАСТРУКТУРЫ (2026-07-31): вложение создаёт актив, а не только
 * разовый бонус к росту.
 *
 * ЗАЧЕМ. `region.infrastructure` не писал ни один тик: поле читали формула ВВП,
 * ставка роста, добыча и бегство капитала, но менять его было нечем. Замер
 * (`server/scripts/probeEconomyLoop.ts`) показал, что деньги на инфраструктуру
 * всё же работают — вкладчик 5% ВВП за 10 лет вырастал в 1,62 раза против 1,24
 * у не вкладывающего, — но исключительно потоком: `infrastructureSpending`
 * входил в ставку роста напрямую, а сама инфраструктура региона оставалась
 * 0,099 и на второй год, и на десятый. Перестал платить — эффект исчез в тот же
 * тик. Экономика была арендной: построить ничего нельзя, можно только платить.
 *
 * МОДЕЛЬ — капитал с амортизацией (тот же скелет, что у модели Солоу): вложение
 * строит, время разрушает, равновесие там, где одно равно другому:
 *
 *     avg_infra_равновесие = BUILD_RATE × (infrastructureSpending / gdp) / DECAY_RATE
 *
 * ПРОПОРЦИОНАЛЬНО, А НЕ К ОБЩЕМУ УРОВНЮ. Вложения задаются страной, а
 * инфраструктура размечена ПО РЕГИОНАМ (0,068…0,950 — авторские данные,
 * `docs/provenance/`). Если тянуть все регионы страны к одному числу, механика
 * сотрёт эту разметку за десяток лет. Поэтому множитель считается для страны, а
 * применяется к каждому региону: относительные различия сохраняются точно, а
 * меняется общий уровень.
 *
 * КАЛИБРОВКА ОТ ДАННЫХ, НЕ ОТ ВКУСА. На старте 1946 медианная интенсивность
 * вложений 0,040 ВВП, медианная инфраструктура 0,321. Отношение BUILD/DECAY =
 * 8,025 выбрано так, чтобы при фактической интенсивности равновесие совпало с
 * фактическим уровнем: мир не едет с первого тика, механика сохраняет
 * авторское состояние, а не переписывает его. Дальше расходятся те, кто менял
 * бюджет: аустерити ИИ роняет интенсивность к 0,025 — равновесие такой страны
 * 0,20, и она медленно ветшает.
 *
 * DECAY 0,008/мес (≈9,6%/год) — быстрее реального износа капитала (2–4%), и это
 * сознательно: период полураспада отклонения ln2/0,008 ≈ 87 месяцев, то есть
 * последствия бюджетного решения игрок видит за 7 лет, а не за 30.
 */
export const INFRASTRUCTURE_BUILD_RATE = 0.0642;
export const INFRASTRUCTURE_DECAY_RATE = 0.008;

