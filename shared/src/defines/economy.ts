/**
 * ИНФЛЯЦИЯ И БЕЗРАБОТИЦА — ПРОЦЕНТЫ (2026-07-31): приращение переведено в те же
 * единицы, что и величина, и появился якорь.
 *
 * ГДЕ БЫЛА ОШИБКА — В ПРИРАЩЕНИИ, НЕ В ПОРОГЕ. Шкалу «процент» независимо
 * задают ЧЕТЫРЕ места: стартовые данные (`economyArchetypes.ts` — инфляция 2–3,
 * безработица 1–5), пороги политики (`STABILITY_*_THRESHOLD` = 5/15/20),
 * схема сценария (`scenario1946Schemas.ts`) и текст мирового факта для LLM
 * (`SimulationEngine.ts`, «inflation surged past crisis levels (20.1)»).
 * Приращение же было ДОЛЕЙ ВВП: `0.1 × дефицит/ВВП`. Один производитель против
 * четырёх потребителей — двигаем производителя.
 *
 * ЗАМЕР ДО ПРАВКИ (`server/scripts/probeScales.ts`, 120 месяцев, сценарий 1946):
 * инфляция ушла с медианы 3,000 всего до 1,817 (коридор 0,471…2,528), порог
 * кризиса 20 не перешла НИ ОДНА страна из 157. Отклик был примерно в сто раз
 * слабее собственной шкалы: при медианном сальдо 13,3% ВВП в месяц старая
 * формула двигала инфляцию на 0,16 пункта в ГОД.
 *
 * ПОЧЕМУ НЕ ПРОСТО ×100. Интегратор без якоря при любом коэффициенте рано или
 * поздно выносит величину за пределы правдоподобия: сальдо в этом сценарии
 * одного знака у всех (доли расходов в данных суммируются в 0,95), и за долгую
 * партию инфляция уехала бы в стойкую дефляцию, а потом упёрлась бы в границу.
 * Упереться в границу не лучше, чем уехать. Поэтому модель — возврат к цели:
 *
 *     цель      = BASELINE + чувствительность × насыщенное(дефицит/ВВП, в п.п.)
 *     инфляция += REVERSION × (цель − инфляция),  затем клип в [MIN, MAX]
 *
 * НАСЫЩЕНИЕ ВХОДА (`FISCAL_PRESSURE_CAP`). Бюджетный блок — соседняя область, и
 * его масштаб сейчас великоват (сальдо ±6…17% ВВП за МЕСЯЦ). Линейный отклик на
 * такой вход даёт бессмыслицу, поэтому давление обрезается по модулю: за
 * порогом сигнал означает «максимальный бюджетный стресс», а не «ещё в десять
 * раз сильнее». Тот же приём защищает механику, если соседний блок пересчитают.
 *
 * АСИММЕТРИЯ ВНИЗ — НЕ ХАК. Цены и зарплаты вниз ходят хуже, чем вверх
 * (downward rigidity): профицит охлаждает инфляцию к базовой линии, но не
 * производит дефляцию так же охотно, как дефицит производит инфляцию. Отсюда
 * разные коэффициенты на две стороны.
 *
 * ЗНАК ПО БЕЗРАБОТИЦЕ СОХРАНЁН КАК БЫЛ: дефицит её повышает. Это спорно
 * (краткосрочный кейнсианский эффект обратный), но это существующая продуктовая
 * семантика «дефицит вреден всему», а не дефект шкалы — менять её в задаче про
 * единицы измерения не следует. Вынесено в `docs/IDEAS.md`.
 *
 * ЧЕМ ЗАПЛАЧЕНО: возврат к ОБЩЕЙ базовой линии стирает архетипный разброс
 * стартовых значений (инфляция 2 против 3, безработица 1/4/5) за несколько лет.
 * Разброс архетипный, а не авторский по странам, и укладывается в шум механики;
 * сохранить его можно только структурным полем в `EconomyState`, а это
 * параллельно редактируемый тип. Названо явно, вынесено в `docs/IDEAS.md`.
 */

