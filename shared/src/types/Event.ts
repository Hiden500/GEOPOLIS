import { type PrimitiveOutcomeRecord } from "./politics/PrimitiveOutcome";

/**
 * Отклонённый примитив в составе события — диагностический хвост, не канон.
 *
 * `verb` необязателен: примитив, провалившийся на структурной схеме, глагола
 * может и не иметь (поле отсутствует или не входит в алфавит).
 */
export interface EventRejectedPrimitive {
  verb?: string | undefined;
  reason: string;
}

export interface Event {

  id: string;

  date: string;

  title: string;

  description: string;

  countries: string[];

  /**
   * Что событие ФАКТИЧЕСКИ изменило в мире — машиночитаемо, рядом с текстом
   * (docs/CONCEPT.md §7.2: «Нарратив пишется только после commit и по
   * фактически применённому результату»).
   *
   * Поле появилось 2026-07-26 по внешнему аудиту. До него потребитель события
   * (интерфейс, летопись, память страны) видел ТОЛЬКО `title`/`description` —
   * сырой текст модели, записанный независимо от того, применился ли хоть один
   * примитив. Проверить текст было не по чему, и «Восстание подавлено» при
   * отклонённой репрессии становилось каноном наравне с настоящим событием.
   *
   * Пусто/отсутствует у событий, к которым примитивы отношения не имеют
   * (чистый нарратив, старый канал `actions`, события до этой правки).
   */
  primitiveOutcomes?: PrimitiveOutcomeRecord[] | undefined;

  /**
   * Что в этом же ответе было ОТКЛОНЕНО и почему — вторая половина того же
   * требования: при частичном применении потребитель обязан уметь отличить
   * заявленное текстом от случившегося.
   *
   * Хранится вместе с событием, а не только в одноразовой диагностике промта,
   * потому что у них разное время жизни: диагностику вычищает следующий рендер
   * промта, а вопрос «этот заголовок описывает всё, что произошло?» остаётся
   * актуальным столько же, сколько само событие.
   */
  rejectedPrimitives?: EventRejectedPrimitive[] | undefined;
}
