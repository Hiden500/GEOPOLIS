import { type ResponseReceipt } from "./ResponseReceipt";

/**
 * Степень подтверждённости ТЕКСТА события фактическим результатом
 * (docs/PRIMITIVES.md §3, решение пользователя 2026-07-27).
 *
 * Значение выводится из результата применения, а не выставляется вызывающим по
 * смыслу текста: `server/src/llm/eventFactuality.ts::deriveEventFactuality`.
 *
 * - `confirmed` — всё, что ответ ПРЕДЛОЖИЛ движку, движок применил. Это ровно
 *   такое утверждение и не больше: текст по-прежнему написан ДО применения и
 *   вправе рассказывать о мире что-то сверх примитивов (речь в Фултоне при
 *   применённом `incite_unrest`). Полная правдивость текста требует второго
 *   вызова модели и отнесена к Милстоуну 1;
 * - `partial` — часть предложенного отклонена (схемой, границей агентности или
 *   предпосылками движка). Текст вправе описывать именно отклонённую часть;
 * - `unconfirmed` — ответ не предлагал движку ничего (чистый нарратив, §4).
 *   Подтверждать нечего — но и утверждать такому тексту нечем, поэтому в
 *   долгую память кампании он не идёт.
 */
export type EventFactuality = "confirmed" | "partial" | "unconfirmed";

/** Общая часть обоих видов записи: текст с датой и своим идентификатором. */
interface EventBase {
  id: string;

  date: string;

  title: string;

  description: string;
}

/**
 * Запись ОТВЕТА модели — месячная проза с квитанцией.
 *
 * `receipt` обязателен, а не опционален: «квитанции нет» не должно читаться как
 * «наверное, всё применилось». Ответ, ничего не применивший, тоже несёт
 * квитанцию — пустую и с `factuality: "unconfirmed"`.
 */
export interface ResponseEvent extends EventBase {
  kind: "response";

  /**
   * ЧТО НА САМОМ ДЕЛЕ произошло — одной структурой (`ResponseReceipt`).
   *
   * До Милстоуна 1 то же самое лежало четырьмя отдельными полями
   * (`countries`, `factuality`, `primitiveOutcomes`, `rejectedPrimitives`), и
   * каждый потребитель — лента событий, летопись, память страны, панель
   * цикла — собирал из них свою картину. Теперь у «что произошло» один
   * источник, и `title`/`description` рядом с ним остаются тем, чем они и
   * являются: текстом, написанным ДО применения, который квитанцией можно
   * ПРОВЕРИТЬ.
   */
  receipt: ResponseReceipt;
}

/**
 * ДАТИРОВАННОЕ событие — один факт из прозы того же ответа, вынесенный
 * структурой (решение пользователя 2026-08-08).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ВИД, А НЕ ПОЛЕ ВНУТРИ ЗАПИСИ ОТВЕТА. Лента кампании должна
 * читаться хронологически — «5 марта 1946 — речь в Фултоне», — а не помесячной
 * простынёй. Но у такой записи не может быть СВОЕЙ квитанции: квитанция
 * описывает, что движок применил из предложенного ОТВЕТОМ, и приписать её
 * одному из пяти фактов месяца значило бы утверждать, что примитивы — следствие
 * именно этого факта. Поэтому здесь ссылка: подтверждённость разрешается по
 * записи ответа, а не выдумывается заново.
 *
 * Текст такой записи — по-прежнему заявление режиссёра, написанное ДО
 * применения. Канонизируется она вместе с прозой того же ответа и по тому же
 * правилу (`docs/PRIMITIVES.md` §3, «Нарратив только после commit»): ответ, не
 * применивший ничего, не оставляет ни прозы, ни датированных событий.
 */
export interface DatedEvent extends EventBase {
  kind: "dated";

  /** `id` записи ответа, вместе с которой событие пришло. */
  responseEventId: string;

  /**
   * Страны, которых событие касается ПО СЛОВАМ МОДЕЛИ, — заявление, а не факт
   * движка.
   *
   * Намеренно НЕ называется так же, как `receipt.countries`: там список выводится
   * из применённых примитивов и означает «мир этих стран действительно
   * изменился». Здесь — «модель написала про эти страны». Одно поле на два
   * смысла рано или поздно прочитали бы как факт.
   *
   * Проверено по `## Country IDs` промта: неизвестный id отбрасывается, само
   * событие остаётся.
   */
  claimedCountries: string[];
}

/**
 * Запись истории кампании: либо ответ модели, либо датированное событие из
 * него. Разбор по `kind` обязателен — тип не даёт прочитать датированную запись
 * так, будто у неё есть квитанция.
 */
export type Event = ResponseEvent | DatedEvent;

/** Записи ответов — единственный вид, у которого есть квитанция. */
export function isResponseEvent(event: Event): event is ResponseEvent {
  return event.kind === "response";
}
