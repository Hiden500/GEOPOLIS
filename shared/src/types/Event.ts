import { type ResponseReceipt } from "./ResponseReceipt";

/**
 * Степень подтверждённости ТЕКСТА события фактическим результатом
 * (docs/PRIMITIVES.md §3, решение пользователя 2026-07-27).
 *
 * Значение выводится из результата применения, а не выставляется вызывающим по
 * смыслу текста: `server/src/llm/eventFactuality.ts::deriveEventFactuality`.
 *
 * - `confirmed` — всё, что ответ ПРЕДЛОЖИЛ движку, движок применил. Это ровно
 *   такое утверждение и не больше: текст по-прежнему написан ДО применения и
 *   вправе рассказывать о мире что-то сверх примитивов (речь в Фултоне при
 *   применённом `incite_unrest`). Полная правдивость текста требует второго
 *   вызова модели и отнесена к Милстоуну 1;
 * - `partial` — часть предложенного отклонена (схемой, границей агентности или
 *   предпосылками движка). Текст вправе описывать именно отклонённую часть;
 * - `unconfirmed` — ответ не предлагал движку ничего (чистый нарратив, §4).
 *   Подтверждать нечего — но и утверждать такому тексту нечем, поэтому в
 *   долгую память кампании он не идёт.
 */
export type EventFactuality = "confirmed" | "partial" | "unconfirmed";

export interface Event {

  id: string;

  date: string;

  title: string;

  description: string;

  /**
   * ЧТО НА САМОМ ДЕЛЕ произошло — одной структурой (`ResponseReceipt`).
   *
   * До Милстоуна 1 то же самое лежало четырьмя отдельными полями
   * (`countries`, `factuality`, `primitiveOutcomes`, `rejectedPrimitives`), и
   * каждый потребитель — лента событий, летопись, память страны, панель
   * цикла — собирал из них свою картину. Теперь у «что произошло» один
   * источник, и `title`/`description` рядом с ним остаются тем, чем они и
   * являются: текстом, написанным ДО применения, который квитанцией можно
   * ПРОВЕРИТЬ.
   *
   * Обязательное поле, а не опциональное: «квитанции нет» не должно читаться
   * как «наверное, всё применилось». Событие без применения к движку тоже
   * несёт квитанцию — пустую и с `factuality: "unconfirmed"`.
   */
  receipt: ResponseReceipt;
}
