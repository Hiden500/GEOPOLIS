import { type EventFactuality } from "./Event";
import { type PrimitiveOutcomeRecord } from "./politics/PrimitiveOutcome";
import { type PrimitiveRejectionRecord } from "./politics/PrimitiveRejection";

/**
 * Квитанция ответа — ЧТО НА САМОМ ДЕЛЕ произошло, одной структурой
 * (docs/PRIMITIVES.md §3, docs/CONCEPT.md §7.2).
 *
 * ЗАЧЕМ. Сырой черновик модели не должен сам становиться историей. До
 * Милстоуна 1 «что произошло» было собрано из кусков, лежащих в разных местах
 * с разным временем жизни: степень подтверждённости — полем события,
 * фактические дельты — вторым полем, отказы — третьим, затронутые страны —
 * четвёртым, отказы старого канала — только в ответе ручки и никогда в
 * состоянии. Каждый потребитель (лента событий, летопись, память страны,
 * панель цикла) собирал свою картину сам, и «событие» означало у них разное.
 *
 * Теперь источник ОДИН. Квитанция строится один раз, в момент применения, из
 * фактического результата — и ровно она уходит в событие, в летопись, в память
 * страны и игроку. Ни один потребитель не считает ничего заново, поэтому
 * разойтись им негде.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Текста модели. `title`/`description` живут в самом событии и
 * остаются написанными ДО применения — квитанция существует как раз для того,
 * чтобы этот текст можно было ПРОВЕРИТЬ, а не чтобы его заменить. Полная
 * правдивость прозы требует второго вызова модели (docs/TODO.md).
 */
export interface ResponseReceipt {
  /** Игровая дата применения — квитанция самодостаточна вне события. */
  date: string;

  /**
   * Повтор уже применённого ответа: ничего не применялось и не отклонялось,
   * мир не тронут. Отдельный флаг, а не «пустые списки»: «применено ноль» и
   * «этот ответ уже был» — разные вещи, и путать их в интерфейсе нельзя.
   */
  duplicate: boolean;

  /**
   * Степень подтверждённости текста фактическим результатом. Выводится из
   * чисел применённого и отклонённого (`deriveEventFactuality`), а не
   * выставляется по смыслу текста.
   */
  factuality: EventFactuality;

  /** Страны, которых ответ фактически коснулся, — из ПРИМЕНЁННОГО. */
  countries: string[];

  /** Регионы, которых ответ фактически коснулся, — из ПРИМЕНЁННОГО. */
  regions: number[];

  /**
   * ЕДИНСТВЕННЫЙ канал ответа: локализуемый отклик по применённым, структурные
   * коды по отклонённым.
   *
   * Поля `actions` здесь больше нет (2026-08-02). Старый канал перестал
   * существовать вместе со своими последними четырьмя типами, а его записи,
   * если модель их всё же пришлёт, приходят сюда отказом `legacyActionsChannel`
   * — тем же способом, что любой другой отказ, и с той же локализуемой
   * причиной. Двух форм отказа в квитанции больше нет.
   */
  primitives: {
    applied: PrimitiveOutcomeRecord[];
    rejected: PrimitiveRejectionRecord[];
  };
}

/**
 * Пустая квитанция: ответ ничего движку не предлагал и ничего не изменил.
 *
 * Живёт рядом с типом, а не у каждого потребителя: «пустая квитанция» — часть
 * контракта, и две её реализации разошлись бы в том, что считать пустотой.
 */
export function emptyResponseReceipt(date: string): ResponseReceipt {
  return {
    date,
    duplicate: false,
    factuality: "unconfirmed",
    countries: [],
    regions: [],
    primitives: { applied: [], rejected: [] },
  };
}
