import { type LocalizedText } from "../i18n/LocalizedText";

/**
 * Локализуемая причина отказа примитива (docs/PRIMITIVES.md §3).
 *
 * Форма — та же, что у отклика на применённый примитив
 * (`PrimitiveOutcomeLine`): ключ + значения + локализованные имена. Причина
 * одна: отказ и отклик читает один и тот же интерфейс, и второй формат
 * означал бы второй словарь и второй способ его разъехаться.
 *
 * ПОЧЕМУ НЕ ГОТОВАЯ СТРОКА. До Милстоуна 1 отказ был английским текстом
 * движка, и этот текст уходил ДВУМ потребителям с несовместимыми
 * требованиями: игроку нужен русский, промту модели — английский. Дешёвой
 * замены «i18n-ключ вместо строки» не существовало — нужен был именно код +
 * параметры + отдельный английский рендер, у каждого из ~20 мест построения
 * причины. Сделано в Милстоуне 1.
 *
 * ЧТО СЮДА НЕ ПОПАДАЕТ. Величина действия, которое НЕ произошло. Прежняя
 * строка несла её дословно — «…would total 0.238 (max 0.45 per turn)», — то
 * есть игрок читал силу приказа, отклонённого движком, хотя по контракту
 * величины не существует до применения (docs/PRIMITIVES.md §1). Граница
 * проведена так: **свойства мира и правил — можно, магнитуда несостоявшегося
 * действия — нельзя.** Порог, кап, текущее недовольство региона, координата
 * оси — свойства мира; «этот примитив добавил бы 0.238» — магнитуда. Числа
 * второго рода живут только в английском рендере для промта
 * (`server/src/primitives/rejections.ts`) и до клиента не доезжают.
 */
export interface PrimitiveRejectionRecord {
  /**
   * Глагол, если он известен. Отсутствует у записи, не дошедшей до алфавита
   * (битый JSON, `verb` вне алфавита).
   */
  verb?: string | undefined;

  /** Ключ i18n внутри namespace `primitiveRejection` клиента. */
  code: string;

  /** Готовые к подстановке значения: пороги, капы, счётчики, текущие величины мира. */
  values?: Record<string, string | number> | undefined;

  /** Имена сущностей мира (регион, группа, страна) — клиент разрешает своей локалью. */
  names?: Record<string, LocalizedText> | undefined;
}
