import { type LocalizedText } from "../i18n/LocalizedText";

/**
 * Локализуемый отклик на применённый примитив (docs/PRIMITIVES.md §4,
 * docs/LOCALIZATION.md).
 *
 * Почему не готовая строка. Движок примитивов возвращает `summary` — сырой
 * английский текст, и документ прямо называет его вспомогательным резюме, а не
 * источником истины. Игроку нужен текст на языке интерфейса, а интерфейс живёт
 * на `react-i18next`, которому нужны КЛЮЧ и ПАРАМЕТРЫ, а не собранная фраза.
 * Поэтому сервер отдаёт разложенную форму: что произошло (ключ), с какими
 * числами (`values`) и над кем (`names`, локализованные имена сущностей мира).
 *
 * Числа в `values` — только фактические дельты из структурных полей результата
 * (`before`/`after`/`delta`), никогда не запрошенные: у насыщенного поля памяти
 * эти два числа расходятся в разы (docs/PRIMITIVES.md §4 — «цифры правдивые,
 * не выдуманные»).
 */
export interface PrimitiveOutcomeLine {
  /** Ключ i18n внутри namespace `primitiveOutcome` клиента. */
  key: string;

  /**
   * Готовые к подстановке значения: числа, доли, идентификаторы перечислений.
   * Ничего, что зависит от локали, здесь быть не должно.
   */
  values?: Record<string, string | number> | undefined;

  /**
   * Имена сущностей мира (регион, группа, страна) как `LocalizedText` — клиент
   * разрешает их своей локалью и подставляет в те же плейсхолдеры, что и
   * `values`. Разделение нужно потому, что интерполяция i18next принимает
   * строку, а выбор языка имени принадлежит клиенту, не серверу.
   */
  names?: Record<string, LocalizedText> | undefined;
}

/**
 * Отклик одного применённого примитива: короткий заголовок + перечисление
 * фактических следов.
 *
 * `verb` — идентификатор глагола (`PrimitiveVerb` движка). Тип здесь `string`
 * намеренно: алфавит объявлен в `server/src/primitives/types.ts`, а `shared`
 * не может зависеть от `server`. Значение всегда корректно по построению —
 * запись собирается из `AppliedPrimitive`, — и потребители используют его как
 * метку, а не как разветвление логики.
 */
export interface PrimitiveOutcomeRecord {
  verb: string;
  headline: PrimitiveOutcomeLine;
  details: PrimitiveOutcomeLine[];
}

/**
 * Одна запись истории места (docs/CONCEPT.md §5.6): «что здесь произошло и
 * когда». Локализуемая по построению, поэтому в отличие от `Event.title`
 * не тащит в состояние заранее переведённый текст.
 *
 * Список капируется (`PLACE_HISTORY_MAX_ENTRIES`) — §5.6 ставит это условием:
 * копят только значимые места, безграничная хроника уже была болью.
 */
export interface PlaceHistoryEntry {
  /** Игровая дата, не wall-clock. */
  date: string;
  /** Глагол, оставивший запись. */
  verb: string;
  line: PrimitiveOutcomeLine;
}
