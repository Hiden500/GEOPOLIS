/**
 * Координаты идеологии на двух непрерывных осях (docs/CONCEPT.md §4.2).
 * Именованный ярлык (`PoliticsState.ideology`) остаётся для читаемости —
 * координаты под ним дают нюанс (СССР, Югославия и Китай под одним ярлыком
 * «коммунизм» стоят в разных точках) и, главное, геометрию недовольства:
 * недовольство группы = дистанция «позиция власти ↔ желаемая позиция группы»,
 * а не таблица «нация X недовольна при режиме Y».
 *
 * Диапазон каждой оси — [-1, +1], два знака после запятой (реализация среза,
 * docs/plans/13_MILESTONE_0_VERTICAL_SLICE.md).
 */
export interface IdeologyCoordinates {
  /** -1 — крайне лево (плановая, обобществление), +1 — крайне право (laissez-faire). */
  economic: number;

  /** -1 — тоталитарный авторитаризм, +1 — полная демократия. */
  political: number;
}

/** Минимум/максимум любой оси координат идеологии. */
export const IDEOLOGY_AXIS_MIN = -1;
export const IDEOLOGY_AXIS_MAX = 1;

/**
 * Максимально возможная евклидова дистанция между двумя позициями на
 * квадрате [-1,1]² — расстояние между противоположными углами, 2√2.
 * Делитель нормировки дистанции в 0..1 (shared/src/utils/discontent.ts).
 */
export const IDEOLOGY_MAX_DISTANCE = Math.SQRT2 * 2;
