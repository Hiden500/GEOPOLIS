/**
 * Форма правления и юридическое положение государства (docs/POLITICS.md).
 *
 * Два независимых вопроса о государстве, которые до Милстоуна 1 модель не
 * различала вовсе:
 *   - `PowerStructure` — КТО фактически осуществляет власть;
 *   - `SovereigntyStatus` + `overlordIds` — КОМУ государство юридически
 *     подчинено.
 *
 * ОТНОШЕНИЕ К `diplomacy.puppets`, НАЗВАННОЕ ПРЯМО. Это не второе имя одного и
 * того же множества. `sovereigntyStatus` — юридическое положение на дату
 * сценария; `puppets` — эффективное следование внешней политике сюзерена
 * (по нему `WarService` втягивает клиентов в войну, а `DiplomacyTick` считает
 * тяготение пары). Множества НЕ равны и не обязаны быть равны: зона оккупации
 * подчинена державе юридически, но собственной внешней политики не имеет
 * вовсе, а спорная администрация (Демократическая Республика Вьетнам при
 * французской претензии) подчинена только на бумаге.
 *
 * Чего они не могут — противоречить друг другу. Марионетка обязана быть
 * несуверенной, и её сюзерен обязан входить в `overlordIds`. Держат это
 * `scripts/map/validate_demographics_1946.py` (до запуска игры) и
 * `server/src/scenarios/__tests__/government1946.test.ts` (по загруженному
 * сценарию).
 *
 * Перечни — `as const` МАССИВЫ, а не голые union-типы: `z.enum()` не выводит
 * литералы из TS-union рантаймово, и рядом со схемой завелась бы вторая копия
 * списка (та же причина и тот же приём, что у `SANCTION_TYPES` в
 * `shared/src/types/DiplomacyState.ts`). Список первичен, тип выводится из него.
 */

/**
 * Кто фактически правит. Перечень описывает МЕХАНИЗМ удержания власти, а не
 * идеологию: идеология живёт отдельно, координатами (`PoliticsState.ideology*`).
 * Одна и та же точка спектра достигается по-разному — партийная диктатура и
 * личный режим стоят рядом по осям, но ведут себя как разные государства.
 */
export const POWER_STRUCTURES = [
  /** Свободная конкуренция партий, смена власти выборами реальна. */
  'competitive_multiparty',
  /** Партии есть и конкурируют, но доступ к власти ограничен цензом/цензурой. */
  'limited_multiparty',
  /** Многопартийность формальна, одна партия не проигрывает. */
  'dominant_party',
  /** Единственная разрешённая партия. */
  'one_party',
  /** Власть держится на лидере, а не на институте, который его поставил. */
  'personalist',
  /** Правит армия как корпорация. */
  'military',
  /** Наследственный двор — источник власти, а не церемония при парламенте. */
  'dynastic_court',
  /** Религиозная иерархия правит непосредственно. */
  'clerical',
  /** Управление метрополии над зависимой территорией. */
  'colonial_administration',
  /** Управление военной администрации победителя. */
  'occupation_administration',
  /** Временная коалиция до учредительных выборов. */
  'provisional_coalition',
  /** Единого центра власти на территории нет. */
  'fragmented',
] as const;

export type PowerStructure = (typeof POWER_STRUCTURES)[number];

/**
 * Юридическое положение субъекта.
 *
 * Различает виды подчинения, которые ведут себя по-разному: доминион ведёт
 * собственную внешнюю политику, мандат подотчётен международному органу, зона
 * оккупации не субъект вовсе. Схлопывание их в «зависимый/независимый» стоило
 * бы ровно того, ради чего перечень заведён.
 */
export const SOVEREIGNTY_STATUSES = [
  /** Независимое государство. `overlordIds` пуст. */
  'sovereign',
  /** Самоуправление при формальной короне метрополии. */
  'dominion',
  /** Внутреннее самоуправление, внешние сношения у метрополии. */
  'protectorate',
  /** Прямое владение метрополии. */
  'colony',
  /** Мандат Лиги Наций. */
  'mandate',
  /** Подопечная территория ООН. */
  'trust_territory',
  /** Совместное управление двух держав — ровно два `overlordIds`. */
  'condominium',
  /** Своё государство под военной оккупацией. */
  'occupied_territory',
  /** Зона раздела оккупированной страны между державами. */
  'occupation_zone',
  /** Территория в аренде у другого государства. */
  'leased_territory',
  /** Власть оспаривается: держава претендует, контроль не бесспорен. */
  'disputed_administration',
] as const;

export type SovereigntyStatus = (typeof SOVEREIGNTY_STATUSES)[number];

/** Единственный статус, требующий ровно двух сюзеренов. */
export const CONDOMINIUM_STATUS: SovereigntyStatus = 'condominium';

/** Единственный статус без сюзерена. */
export const SOVEREIGN_STATUS: SovereigntyStatus = 'sovereign';

/**
 * Статус, который получает СУВЕРЕННОЕ государство, подчинённое в партии
 * (примитив `puppet`, `server/src/primitives/subordination.ts`).
 *
 * `protectorate` выбран из перечня, а не заведён новым значением: он и есть
 * «внутреннее самоуправление, внешние сношения у метрополии», то есть ровно то,
 * чем вассалитет отличается от аннексии. Отдельный статус «вассал» дублировал
 * бы существующий и потребовал бы решать, чем они различаются, — а различия нет.
 */
export const VASSALAGE_DEFAULT_STATUS: SovereigntyStatus = 'protectorate';

/**
 * Статусы, при которых `overlordIds` называет ПРЕТЕНДЕНТА либо администратора,
 * а не патрона, — то есть подчинение не означает следования внешней политике.
 *
 * Нужен там, где новый слой сверяется со старым: требовать «несуверенный ⇒
 * марионетка» нельзя именно из-за них (по боевым данным 1946 — 14 субъектов:
 * десять зон оккупации, Япония и советская Маньчжурия, ДРВ и Республика
 * Индонезия). Обратное требование — «марионетка ⇒ несуверенная» — верно всегда
 * и проверяется.
 */
export const NON_VASSAL_SUBORDINATION_STATUSES: readonly SovereigntyStatus[] = [
  'occupied_territory',
  'occupation_zone',
  'disputed_administration',
];
