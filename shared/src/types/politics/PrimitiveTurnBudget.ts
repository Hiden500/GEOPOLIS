/**
 * Бюджет примитивов НА ИГРОВОЙ ХОД (docs/PRIMITIVES.md §4).
 *
 * Почему в состоянии партии, а не в локальных переменных вызова. Капы §4
 * («≤10 мягких + ≤1 структурный», «один verb на цель», «потолок накопления на
 * поле») существуют ровно за тем, чтобы кламп величины нельзя было обойти
 * частотой. Пока движок звали один раз за ответ модели, «один вызов = один ход»
 * держалось само собой и счётчики внутри вызова были достаточны. С появлением
 * ручки `POST /primitives/apply` это перестало быть правдой: каждый клик игрока
 * — отдельный вызов, число вызовов за месяц ничем не ограничено, и десять
 * кликов «Подавить» по одной паре (регион, группа) упирали оба поля памяти в
 * потолок — ровно то, что коридор магнитуды запрещает делать одним примитивом.
 * Замер на данных 1946 (регион 68 / `estonians`, десять `repress(mild)`):
 * один батч — `suppression` 0.238, десять отдельных вызовов — 1.000.
 *
 * Поэтому единица учёта — игровой ход, а он в состоянии один на всех: ответ
 * модели и приказ игрока тратят ОДИН бюджет. Иначе обход просто переезжает на
 * другой канал.
 *
 * **Ключ обнуления — дата, а не отдельный вызов reset.** Бюджет помнит, к
 * какому `currentDate` он относится; бюджет чужой даты читается как пустой и
 * перезаписывается при первой же записи. Это не оптимизация, а свойство
 * надёжности: обнулять явно пришлось бы в тике, и любой путь, двигающий дату
 * мимо этого места, молча унёс бы остатки прошлого месяца в новый (или,
 * наоборот, забыл бы обнулить и заблокировал законный ход). Дата — сам факт
 * «это другой ход», её невозможно забыть обновить.
 *
 * **Размер в сейве.** Бюджет живёт только за ТЕКУЩИЙ ход и обнуляется сменой
 * даты — это и есть главная граница. Но число ключей растёт НЕ как число
 * примитивов: ключи ключуются целями и парами (регион, группа, поле), а один
 * примитив трогает столько целей, сколько групп живёт в регионе, плюс соседние
 * регионы у отклика на уступку. Замеры на данных 1946 (уточнено ревью
 * 2026-07-26, прежняя формулировка «ключей не больше, чем примитивов»
 * занижала):
 *
 * - семь `grant_autonomy` по кризисным регионам — 21 ключ `targetUses` и 56
 *   ключей `impactAccrued`, 4534 байта JSON;
 * - одна `repress` по региону из четырёх групп без указания группы — 12 ключей
 *   (4 + 8) от ОДНОГО примитива.
 *
 * Верхняя граница конечна и выводится из капов: `targetUses` ≤ (мягкие +
 * структурные за ход) × (групп в регионе + затронутых соседей), `impactAccrued`
 * — то же, умноженное на число полей памяти (4). Сегодня это килобайты, потому
 * что демографией размечены 14 регионов. При полной демо-разметке Милстоуна 2
 * множитель «групп в регионе» перестанет быть мелким, и размер надо мерить
 * заново, а не ссылаться на эту оценку (docs/TODO.md).
 */
export interface PrimitiveTurnBudget {
  /**
   * Игровая дата (`GameState.currentDate`), за которую накоплены счётчики.
   * Не совпала с текущей — бюджет считается пустым (см. `turnBudgetFor`).
   */
  date: string;

  /** Сколько мягких примитивов уже применено/списано за этот ход. */
  softUsed: number;

  /** Сколько структурных примитивов уже применено/списано за этот ход. */
  structuralUsed: number;

  /**
   * Сколько раз глагол применялся к цели за ход. Ключ строит движок
   * (`verb -> entity`), здесь это непрозрачная строка: состав ключа —
   * внутреннее дело движка, и хранение его формы в общем типе сделало бы
   * изменение ключа breaking change формата сейва без нужды.
   */
  targetUses: Record<string, number>;

  /**
   * Накопленный ПОЛОЖИТЕЛЬНЫЙ след в памяти воздействий за ход. Ключ — тройка
   * (поле, регион, группа), строит тоже движок.
   */
  impactAccrued: Record<string, number>;
}

/** Пустой бюджет хода для даты — старт партии и первая запись в новом месяце. */
export function emptyPrimitiveTurnBudget(date: string): PrimitiveTurnBudget {
  return { date, softUsed: 0, structuralUsed: 0, targetUses: {}, impactAccrued: {} };
}
