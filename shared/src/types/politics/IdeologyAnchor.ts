import { type LocalizedText } from "../i18n/LocalizedText";
import { type IdeologyCoordinates } from "./Ideology";

/**
 * Именованная точка спектра — историческое имя вместо склейки двух ступеней
 * шкалы (`docs/CONCEPT.md` §4.2, каталог зон 2026-07-27).
 *
 * Склейка «Госуправляемая экономика · Закрытая диктатура» честна, но безлика:
 * она не сообщает, что речь о франкистской Испании. Якорь накрывает небольшую
 * окрестность и даёт ей имя эпохи.
 *
 * ПОЧЕМУ ИМЯ ЛЕЖИТ В ДАННЫХ, А НЕ В СЛОВАРЕ ИНТЕРФЕЙСА. Множество якорей
 * задаёт СЦЕНАРИЙ: «Перонизм» и «Либерализм Нового курса» осмысленны в 1946 и
 * бессмысленны в 1836, а мод принесёт свои. Строка, множество которой
 * расширяется контентом, обязана приходить вместе с контентом — иначе
 * добавление сценария потребует правки клиентских словарей. Ступени шкалы —
 * обратный случай и живут ключами (`shared/src/defines/ideologyBands.ts`).
 * Критерий — `docs/LOCALIZATION.md`.
 */
export interface IdeologyAnchor {
  /** Стабильный идентификатор: `state_socialism`, `peronism`. Не отображается. */
  id: string;

  /** Центр окрестности на тех же осях, что координаты страны. */
  center: IdeologyCoordinates;

  /**
   * Радиус окрестности в единицах координат (евклидово расстояние). Якоря
   * могут перекрываться — побеждает ближайший по расстоянию, поэтому радиус
   * задаёт «докуда имя ещё применимо», а не монопольную зону.
   */
  radius: number;

  /** Отображаемое имя. Именно здесь живут переводы: это контент сценария. */
  name: LocalizedText;
}
