import { type LocalizedText } from "./i18n/LocalizedText";

/**
 * Машина состояний кампании (docs/CONCEPT.md §7.1 и §6).
 *
 * ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ. До Милстоуна 1 состояния кампании в проекте не было
 * вовсе: партия не умела кончаться и не умела продолжаться за другую страну.
 * Пока страны нельзя было создавать и распускать, это было честным пробелом;
 * с жизненным циклом (§7.1) оба перехода становятся достижимыми одним
 * структурным примитивом, и «кто теперь игрок» обязано быть свойством
 * СОСТОЯНИЯ, а не выводиться заново каждым потребителем.
 *
 * ГЛАВНОЕ ПРАВИЛО (§6): game over — **вычисление движка**, а не текст модели, и
 * он **узкий**. Раскол, переворот, оккупация всех регионов и превращение в
 * сателлита — продолжения, а не концы. Конец один: государства игрока больше
 * не существует как субъекта, и преемника, за которого можно играть, нет.
 *
 * ПОЧЕМУ ЗДЕСЬ ИМЕНА, А НЕ ИДЕНТИФИКАТОРЫ. Всё, что относится к ПРОШЛОМУ
 * (распавшийся предшественник, поглотившая держава), хранится как
 * `LocalizedText`, а не как id страны. Причина не в удобстве интерфейса:
 * предшественник по построению уже удалён из ростера, поэтому ссылка на него
 * была бы висячей в момент своего создания — то есть проверка «ноль висячих
 * ссылок» (§7.1) либо валилась бы на штатном исходе, либо получала бы
 * исключение, которое обесценивает её саму. Живой ссылкой остаётся только то,
 * что игрок обязан выбрать: `successorCountryIds`.
 */

/**
 * Почему кампания окончена — структурный код, а не строка.
 *
 * Та же причина, что у `PrimitiveRejection` (`server/src/primitives/rejections.ts`):
 * причина уходит игроку локализованным текстом, и одна английская строка не
 * может обслужить оба языка. Ветка без рендера в клиентском словаре видна как
 * недостающий ключ, а не как «undefined» в интерфейсе.
 */
export type DefeatReason =
  /**
   * Государство распущено, и ни одного осколка, за который можно продолжить, не
   * возникло: все регионы ушли другим субъектам.
   */
  | { code: "dissolvedWithoutSuccessor" }
  /** Государство поглощено конкретной державой (аннексия, не оккупация). */
  | { code: "absorbed"; by: LocalizedText };

export type CampaignStatus = CampaignState["status"];

export type CampaignState =
  /** Штатный ход партии. */
  | { status: "active" }
  /**
   * Государство игрока распалось на несколько осколков, и партия ждёт, за какой
   * из них он продолжит (§7.1: `active → succession_choice_pending → active`).
   *
   * Это НЕ поражение и не пауза «пока не решишь»: §6 прямо называет распад
   * продолжением кампании. Выбор осколка служит и подтверждением необратимого
   * действия (§7.2) — режиссёру не запрещено расколоть страну игрока, но
   * решить, кем он останется, вправе только сам игрок.
   */
  | {
      status: "succession_choice_pending";
      /** Имя распавшегося государства — для интерфейса, не ссылка (см. шапку). */
      predecessor: LocalizedText;
      /** Осколки, между которыми выбирает игрок. Живые ссылки на страны. */
      successorCountryIds: string[];
      /** Игровая дата перехода. */
      since: string;
    }
  /** Единственный конец кампании (§6). */
  | { status: "defeated"; reason: DefeatReason; since: string };

/** Стартовое состояние партии — вынесено сюда, чтобы «активная» была одна на всех. */
export function activeCampaign(): CampaignState {
  return { status: "active" };
}
