/**
 * Версия формата сейва (docs/plans/01_PERSISTENCE_STATE.md). Несовпадение
 * при загрузке — честный отказ, без миграций (пока не понадобятся).
 *
 * v2 (2026-07-10, docs/plans/02_LLM_CONTRACT.md, Шаг 3): новое обязательное
 * поле GameState.chronicle — breaking change формата, старые сейвы (v1)
 * честно отклоняются, не молча ломаются.
 *
 * v3 (2026-07-11, docs/plans/03_MODIFIERS_COMMANDS.md, Шаг 2): новое
 * обязательное поле GameState.modifiers — та же логика честного отказа,
 * старые сейвы (v2) отклоняются.
 *
 * v4 (2026-07-26, docs/plans/13_MILESTONE_0_VERTICAL_SLICE.md, сессия A): три
 * новых обязательных поля GameState — ethnicGroups, groupImpactMemory,
 * regionCrisisLatch (демо-состав и память воздействий, docs/CONCEPT.md §4.1).
 * Старые сейвы (v3) отклоняются: без каталога групп движок не выведет
 * недовольство ни для одного региона.
 *
 * v5 (2026-07-26, тот же план, сессия B): новое обязательное поле
 * GameState.primitiveBatchKeys — журнал idempotency-ключей применённых батчей
 * примитивов (docs/CONCEPT.md §7.2). Сейв v4 без него загрузился бы с
 * `undefined` вместо массива, то есть с отключённой защитой от двойного
 * применения — молча и ровно там, где она нужна. Честный отказ вместо
 * тихой деградации.
 *
 * v6 (2026-07-26, тот же план, доводка по ревью сессии B): новое обязательное
 * поле GameState.primitiveTurnBudget — счётчики капов примитивов на игровой ход
 * (docs/PRIMITIVES.md §4). Сейв v5 без него загрузился бы с `undefined` вместо
 * бюджета, то есть с капами, снова действующими «за вызов», а не «за ход»:
 * десять отдельных приказов в одном месяце обошли бы коридор магнитуды
 * частотой. Та же логика честного отказа — молча деградировать защите нельзя.
 *
 * v7 (2026-07-26, правки по внешнему аудиту): новое обязательное поле
 * GameState.primitiveNoopBatchKeys — отдельное кольцо ключей для батчей, ничего
 * не применивших (docs/PRIMITIVES.md §3). Сейв v6 без него загрузился бы с
 * `undefined`, и первая же запись ключа упала бы на `.includes` несуществующего
 * массива. Тот же честный отказ.
 *
 * v8 (2026-07-27, решение пользователя по итогам внешнего аудита): новое
 * обязательное поле Event.factuality — степень подтверждённости текста события
 * фактическим результатом (docs/PRIMITIVES.md §3). Сейв v7 без него загрузился
 * бы с `undefined` у каждого события, а летопись читает это поле, чтобы не
 * пускать в долгую память кампании неподтверждённые утверждения: неизвестное
 * значение пришлось бы трактовать либо как «подтверждено» (вернуть ту самую
 * ложь), либо как «нет» (молча стереть летопись старой партии). Оба варианта
 * хуже честного отказа.
 *
 * v9 (2026-07-27, Милстоун 1, сессия «Контракты ядра»): `Event` несёт квитанцию
 * `receipt` (`ResponseReceipt`) вместо четырёх отдельных полей — `countries`,
 * `factuality`, `primitiveOutcomes`, `rejectedPrimitives`. Сейв v8 загрузился
 * бы с событиями без квитанции, а её читают и летопись (что взять в долгую
 * память кампании), и «память страны» (какие события касаются этой страны):
 * отсутствие поля пришлось бы трактовать либо как «подтверждено и никого не
 * касается», либо как «ничего не известно». Первое возвращает ту самую ложь,
 * второе молча стирает историю старой партии — оба хуже честного отказа.
 *
 * v10 (2026-07-27, Милстоун 1, сессия «Жизненный цикл государств»): два
 * изменения формы состояния, оба несовместимые молча.
 *   - новое обязательное поле `GameState.campaign` — состояние кампании
 *     (`active` / `succession_choice_pending` / `defeated`, docs/CONCEPT.md
 *     §7.1). Сейв v9 без него загрузился бы с `undefined`, а «состояния нет»
 *     нельзя трактовать ни как «партия активна» (тогда проигранная партия
 *     воскресает), ни как «партия окончена» (тогда живая партия умирает);
 *   - `llmSpotlightCursor` (индекс в пуле) заменён на `llmSpotlightCountryId`
 *     (идентификатор последней показанной страны). Старое число в новом поле
 *     не значит ничего, а молча продолжить с индекса нельзя: пул
 *     пересобирается из состава стран, и после первого же раскола индекс
 *     указывает на другую страну.
 *
 * Миграции по-прежнему нет, и это по-прежнему осознанно: играбельных
 * долгоживущих партий на локальной разработке нет, а миграция контракта, ещё
 * не устоявшегося (алфавит расширяется с 5 глаголов до 18 в следующей сессии),
 * пришлось бы переписывать вместе с ним.
 */
