import { type Event } from "@shared/types/Event";
import { type GameState } from "@shared/types/GameState";
import { describeOutcomesForPrompt } from "../../primitives/outcomes";

/**
 * Сколько последних записей завершившегося года попадает в одну
 * строку-summary летописи — тот же принцип "cheap window", что
 * getRecentTitlesLine/getRecentEventsInfo в LLMService.ts (.slice(-N)), не
 * новая эвристика. "3-5 строк на год" из плана — трактовка: до 5
 * записей, склеенных через "; " в одну строку промта, не 5 физических
 * строк.
 */
const CHRONICLE_TITLES_PER_YEAR = 5;

/**
 * Что год оставляет в летописи — по ФАКТУ, а не по заголовку
 * (решение пользователя 2026-07-27, docs/PRIMITIVES.md §3).
 *
 * Летопись — единственная память кампании, которая живёт всю партию и целиком
 * уходит в каждый промт. Ложное утверждение в ней дороже пропущенного: его
 * модель будет считать прошлым десятилетиями, тогда как пропуск стоит одной
 * забытой строки при живом состоянии мира, истории места и объектах карты.
 * Отсюда правило по каждому классу события:
 *
 *   - `confirmed` — заголовок дословно. Всё, что ответ предлагал движку, движок
 *     применил; более сильного основания доверять тексту у нас нет и не будет
 *     до второго вызова модели (Милстоун 1). Граница названа прямо: это НЕ
 *     означает, что каждое предложение заголовка истинно, — только что
 *     отклонённой части, которую он мог бы описывать, не существует;
 *   - `partial` — заголовок НЕ берётся вовсе, вместо него идут фактические
 *     следы применённых примитивов (`Event.primitiveOutcomes` через
 *     `describeOutcomesForPrompt`). Именно здесь жил разрыв: сырой текст вправе
 *     описывать отклонённую половину, и через год он сворачивался в
 *     многолетнюю память кампании как факт. Частично применённое событие
 *     остаётся в ленте игрока с пометкой, но в летопись доносит только то, что
 *     реально легло в мир;
 *   - `unconfirmed` — не попадает. Чистый нарратив ничего движку не предлагал,
 *     подтверждать нечего; фоновым слоем он остаётся в `eventHistory`, в
 *     «памяти страны» и в `## Recent Events`, но постоянной историей кампании
 *     не становится.
 *
 * ГРАНИЦА, названная явно: правило действует только здесь. «Память страны»
 * (`LLMService.getRecentTitlesLine`) и `## Recent Events` по-прежнему берут
 * `Event.title` дословно, включая частично подтверждённые. Это осознанно —
 * окно там короткое (последние N событий) и самоочищается, а летопись
 * накапливается всю партию. Приведение самого ТЕКСТА к факту требует второго
 * вызова модели («перепиши по фактам») и отнесено к Милстоуну 1
 * (docs/TODO.md).
 */
function chronicleLine(event: Event): string | undefined {
  switch (event.factuality) {
    case "confirmed":
      return event.title;
    case "partial": {
      // У частично применённого события следы могут быть только в старом канале
      // `actions` — машиночитаемого результата у него нет, и выдумывать его
      // здесь не из чего. Тогда год не получает от этого события ничего.
      const applied = describeOutcomesForPrompt(event.primitiveOutcomes ?? []);
      return applied.length > 0 ? `applied: ${applied}` : undefined;
    }
    case "unconfirmed":
      return undefined;
  }
}

/**
 * Раз в год (январский тик, SimulationEngine.ts) сворачивает подтверждённое из
 * eventHistory завершившегося года в одну запись летописи —
 * docs/plans/02_LLM_CONTRACT.md, Шаг 3. Вызывается уже ПОСЛЕ того как
 * game.currentDate продвинута на январь нового года — "только что
 * закончившийся год" вычисляется как currentYear - 1.
 *
 * Детерминированная конкатенация, без вызова LLM (docs/DECISIONS.md,
 * 2026-07-05: сначала дешёвый дефолт, LLM-сжатие — только если окажется
 * недостаточным на практике).
 *
 * Что именно попадает в запись — см. `chronicleLine` выше: летопись строится по
 * фактическому результату событий, а не по их заголовкам.
 */
export function chronicleTick(game: GameState): void {
  const currentYear = Number(game.currentDate.split("-")[0]);
  const endedYear = currentYear - 1;
  const yearPrefix = `${endedYear}-`;

  const lines = game.eventHistory
    .filter(e => e.date.startsWith(yearPrefix))
    .map(chronicleLine)
    .filter((line): line is string => line !== undefined && line.length > 0);

  // Пустой год — и когда LLM не отвечала весь год, и когда весь год состоял из
  // неподтверждённых заявлений. Разницы для летописи нет: подтверждённого
  // прошлого не осталось ни в том, ни в другом случае, а пустая запись «1946: »
  // читалась бы моделью как год, о котором известно ничего, то есть как факт.
  if (lines.length === 0) return;

  game.chronicle.push({
    year: endedYear,
    summary: lines.slice(-CHRONICLE_TITLES_PER_YEAR).join("; "),
  });
}
