import { type Country } from "@shared/types/Country";

/**
 * ЕДИНСТВЕННОЕ определение дохода и базы бюджетной росписи на сервере.
 *
 * Формула жила в трёх копиях, и копии разошлись: тик считал доли от
 * располагаемого дохода, `PUT /budget` и команды бюджета ИИ — от полного.
 * Игрок, сохранивший роспись, видел баланс, расходящийся с тем, который через
 * секунду посчитает ход, ровно на `(1 − Σдолей) × importSpending`. Поэтому
 * функции здесь, а не рядом с каждым потребителем: у базы росписи должно быть
 * одно место, где её можно поменять.
 *
 * Кто вызывает: `EconomyTick.updateBudget`, `CountryService.updateBudget`
 * (`PUT /budget`), команды бюджета в `commands/economy.ts` (правила ИИ),
 * а `grossIncome` — ещё и читатели, которым нужен знаменатель-доход
 * (`AiBehaviorTick`, `PoliticsTick`).
 */

/** Доход государства за месяц — сумма всех источников, до любых расходов. */
export function grossIncome(country: Country): number {
  const e = country.economy;
  return e.taxRevenue + e.exportIncome + e.stateEnterpriseIncome + e.otherIncome;
}

/**
 * База, от которой считаются пять дискреционных статей: доход за вычетом
 * импорта (решение пользователя 2026-08-03, `docs/decisions/2026-08.md`
 * §«2026-08-04 — Импорт вошёл в роспись»). Импорт — обязательный платёж, а не
 * строка росписи: сырьё закупается до того, как государство распределяет
 * дискреционные статьи, и доли расписывают ТО, ЧТО ОСТАЛОСЬ.
 *
 * Кламп не косметика: страна, чей импорт превысил доход, иначе получила бы
 * ОТРИЦАТЕЛЬНЫЕ расходы — то есть доход из ниоткуда.
 */
export function disposableIncome(country: Country): number {
  return Math.max(0, grossIncome(country) - country.economy.importSpending);
}
