import { z } from "zod";
import { primitiveSchema, MAX_PRIMITIVES_PER_BATCH } from "../primitives/primitiveSchemas";
import { MAX_DATED_EVENTS } from "./datedEvents";

/**
 * Схемы ОТВЕТА модели — транспортная форма верхнего уровня и схема генерации
 * для провайдеров.
 *
 * Файл заменил `actionSchemas.ts` (2026-08-02), и замена не косметическая:
 * union действий старого канала перестал существовать вместе с самим каналом.
 * Последние четыре его типа — `guarantee`, `research_shift`, `production_shift`,
 * `build_extraction` — стали глаголами алфавита примитивов, где величину
 * считает движок, отказ приходит структурным кодом, а результат команды
 * проверяется. Держать после этого файл с именем «схемы действий» и одним
 * конвертом внутри значило бы оставить пустую комнату с табличкой.
 */

/**
 * Транспортный конверт ответа LLM — только форма верхнего уровня. Провал здесь
 * бракует ответ целиком (JSON битый, нет `descriptions`).
 *
 * `actions` ПРИНИМАЕТСЯ, но не применяется, и это осознанная асимметрия.
 * Канала больше нет: схема генерации его не предлагает, промт о нём не
 * рассказывает. Но локальные модели импровизируют по памяти о старом контракте,
 * и молча съеденный массив вернул бы ровно тот дефект, ради которого канал и
 * сносился, — модель считает применённым то, чего движок не читал. Поэтому поле
 * объявлено, а непустое значение превращается в отказ с кодом
 * `legacyActionsChannel` (`LLMService.processResponse`): модель узнаёт о
 * несуществующем канале из отказа, а не из молчания.
 *
 * Верхнего предела длины у него нет намеренно: содержимое никуда не
 * сохраняется и в промт не уезжает — в диагностику идёт только СЧЁТЧИК.
 */
export const LLMResponseEnvelopeSchema = z.object({
  title: z.string().optional(),
  descriptions: z.string({ error: "Missing descriptions field" }).min(1, "Missing descriptions field"),
  actions: z.array(z.unknown()).optional(),
  /**
   * Примитивы воздействия (docs/PRIMITIVES.md) — единственный канал, которым
   * ответ модели меняет мир. Здесь только `unknown[]`: каждый элемент
   * разбирается по отдельности (`parsePrimitives`), чтобы один битый примитив
   * не ронял весь ответ. Необязательный: ответ без примитивов законен — месяц
   * без режиссуры обычное дело. Кап длины проверяет `parsePrimitives`, он же
   * сообщает причину, а не молча отбрасывает хвост.
   */
  primitives: z.array(z.unknown(), "Invalid primitives field").optional(),
  /**
   * Датированные события — факты из той же прозы, вынесенные структурой
   * (`llm/datedEvents.ts`). Здесь снова `unknown[]`: элемент разбирается по
   * отдельности, чтобы одна кривая дата не роняла ответ вместе с примитивами.
   * Необязательное: месяц без датируемого события законен, и требовать
   * непустой массив значило бы заказывать модели выдумывать событие ради поля.
   */
  events: z.array(z.unknown(), "Invalid events field").optional(),
});

/**
 * Форма ОДНОГО датированного события в схеме генерации.
 *
 * Объявлена здесь, а не в `datedEvents.ts`: там разбор ЧУЖОГО ответа (принимает
 * что угодно и объясняет, что не так), здесь — направление генерации заранее.
 * Поля обязательны все три, потому что событие без даты или без заголовка не
 * событие, а обрывок прозы; `countries` необязателен — это заявление модели,
 * без которого запись остаётся полноценной.
 *
 * Урок чужой схемы (`.agent/reference/open-historia-review.md` §2.6): поле, не
 * объявленное здесь, строгий провайдер модели эмитировать не даст, даже если
 * прикладной код его читает.
 */
const datedEventSchema = z.object({
  date: z.string(),
  title: z.string(),
  description: z.string(),
  countries: z.array(z.string()),
});

/**
 * Схема ТОЛЬКО для генерации структурированного ответа провайдером
 * (`GeminiProvider`, `LocalOpenAIProvider`) — строгая, `title` обязателен: её
 * роль в том, чтобы направлять генерацию заранее, а не разбирать чужой
 * произвольный ответ.
 *
 * Поля объявлены в порядке `title → descriptions → primitives`:
 * `z.toJSONSchema()` эмитит `required` в порядке объявления, и порядок важен
 * для совпадения с ожиданиями structured output (`GeminiProvider.test.ts`).
 *
 * Массива `actions` здесь НЕТ, и это главная строчка файла: закрытые enum'ы
 * глаголов и качественных параметров прямо в схеме — машинная формулировка
 * правила «LLM не задаёт величины» на стороне модели, а не только на стороне
 * валидатора (docs/PRIMITIVES.md §1). Пока рядом лежал свободный `actions`,
 * формулировка обходилась сменой канала.
 */
export const ProviderResponseSchema = z.object({
  title: z.string(),
  descriptions: z.string(),
  primitives: z.array(primitiveSchema).max(MAX_PRIMITIVES_PER_BATCH),
  events: z.array(datedEventSchema).max(MAX_DATED_EVENTS),
});
