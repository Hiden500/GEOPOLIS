import { type z } from "zod";

/**
 * Абстракция автоматизированного LLM-провайдера (docs/TODO.md, P2.5) —
 * заменяет ручной copy-paste цикл прямым вызовом внешнего API. Единственный
 * метод намеренно узкий: провайдер получает готовый промт (уже собранный
 * `LLMService.generatePrompt()`) и возвращает сырой текст ответа — ровно то,
 * что раньше вставлялось вручную в "Ответ LLM". Вся валидация/применение
 * остаются в `LLMService.processResponse()`, провайдер её не дублирует.
 */
export interface LLMProvider {
  /**
   * @param responseSchema необязательная Zod-схема ожидаемого ответа. Нужна
   *   потому, что цикл мира — не единственный structured-output запрос:
   *   перевод свободного приказа игрока в примитивы (docs/PRIMITIVES.md §1,
   *   гибридный интерфейс) ждёт другую форму ответа. Опущена — используется
   *   схема мирового цикла, поведение прежних вызовов не меняется.
   *
   *   ЗДЕСЬ ИМЕННО ZOD, А НЕ ГОТОВАЯ СХЕМА ПРОВАЙДЕРА. Диалекты structured
   *   output различаются: Gemini требует своих обогащений (`toProviderSchema`),
   *   OpenAI-совместимый рантайм — обычный JSON Schema с `strict`-ужесточением.
   *   Пока реализация была одна, конвертацию делал вызывающий; со вторым
   *   провайдером это означало бы, что роутер знает, к кому подключён движок, и
   *   способен отдать локальной модели диалект Gemini. Конвертирует каждый
   *   провайдер сам: вызывающий описывает ФОРМУ ответа, а не способ объяснить
   *   её конкретному API.
   */
  generateResponse(prompt: string, responseSchema?: z.ZodType): Promise<string>;
}
