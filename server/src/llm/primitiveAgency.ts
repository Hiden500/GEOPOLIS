/**
 * Глаголы, которые режиссёр не применяет за игрока. Выводятся из словаря, а не
 * дублируют его: два источника разошлись бы ровно так же, как разошлись список
 * и алфавит.
 */
export const PLAYER_DECISION_VERBS: readonly PrimitiveVerb[] = (
  Object.entries(VERB_AGENCY) as [PrimitiveVerb, AgencySide][]
)
  .filter(([, side]) => side === "playerDecision")
  .map(([verb]) => verb);

export function isPlayerDecisionVerb(verb: PrimitiveVerb): boolean {
  return VERB_AGENCY[verb] === "playerDecision";
}

export interface AgencySplit {
  allowed: Primitive[];
  refused: RejectedPrimitive[];
}

/**
 * ПОЧЕМУ ОТСЕВ ЗДЕСЬ НЕ ОТКАТЫВАЕТ ВЕСЬ ОТВЕТ (решено 2026-07-26 повторной
 * верификацией внешнего аудита; docs/PRIMITIVES.md §3–§4).
 *
 * Правило класса «отказ структурного примитива отклоняет весь батч» выполняется
 * внутри движка (`applyPrimitiveBatch`), но этот фильтр снимает запрещённый
 * структурный ДО движка, и допустимые мягкие уходят туда отдельным батчем. То
 * есть ответ «поднять волнения в регионе игрока + провести за игрока реформу»
 * отклоняет реформу и ПРИМЕНЯЕТ волнения. Разобрано и оставлено намеренно, а
 * правило приведено к поведению — по трём причинам.
 *
 * 1. Отказ здесь — не «так не бывает», а «это не твоё решение». Предпосылка
 *    выполнима, мир такую реформу принял бы; неверен только автор. Проектное
 *    намерение границы записано абзацем выше: давление приходит извне, ОТВЕТ
 *    выбирает игрок. Применить давление и оставить ответ игроку — это и есть
 *    задуманный исход, а не полусобытие.
 * 2. Откат батча уничтожил бы само предложение. Нарратив канонизируется только
 *    при `appliedChange` (`LLMService.processResponse`): откатив мягкие, мы
 *    получаем ответ, не применивший ничего, — события нет, `title`/`descriptions`
 *    клиенту не отдаются, и текст «власти могут пойти на уступку» до игрока не
 *    доходит. Граница, существующая ради выбора игрока, стирала бы выбор.
 * 3. Обхода не открывает, и это свойство конструкции, а не удача: фильтр умеет
 *    ТОЛЬКО удалять примитивы. Ни одного состояния мира, недостижимого ответом
 *    без запрещённого структурного, добавление этого структурного не открывает —
 *    модель может лишь потерять его. Удалённое движка не достигает, поэтому и
 *    вызвать отказ движка (со всеми его откатами) оно тоже не может.
 *
 * Цена названа прямо: событие всё-таки записывается, и его СЫРОЙ текст может
 * утверждать реформу, которой не было. Машиночитаемо это видно —
 * квитанция события (`Event.receipt.primitives.rejected`) несёт отказ этого
 * фильтра наравне с отказами движка, — но текст по факту не переписывается
 * (второй вызов модели, docs/TODO.md).
 */

/**
 * Делит примитивы модели на допустимые и отклонённые по границе агентности.
 * Форма отказа — та же `RejectedPrimitive`, что у движка: потребителю
 * (диагностика, интерфейс) незачем знать, на каком слое отказали.
 */
export function splitByAgency(
  primitives: readonly Primitive[],
  playerCountryId: string,
  playerName: LocalizedText = { en: playerCountryId, ru: playerCountryId }
): AgencySplit {
  const allowed: Primitive[] = [];
  const refused: RejectedPrimitive[] = [];

  for (const primitive of primitives) {
    if (primitive.sourceCountryId === playerCountryId && isPlayerDecisionVerb(primitive.verb)) {
      refused.push({
        verb: primitive.verb,
        sourceCountryId: primitive.sourceCountryId,
        rejection: {
          code: "agencyPlayerDecision",
          verb: primitive.verb,
          player: playerName,
        },
      });
      continue;
    }
    allowed.push(primitive);
  }

  return { allowed, refused };
}
