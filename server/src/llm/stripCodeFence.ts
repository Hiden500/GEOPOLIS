/**
 * Забор целиком: необязательные пробелы, ``` с необязательным языком, тело,
 * закрывающие ```. Тело берётся лениво, чтобы закрывающим считался ПОСЛЕДНИЙ
 * забор, а не первый попавшийся внутри строки.
 */
const FENCED = /^\s*```[^\S\r\n]*[a-zA-Z0-9_-]*[^\S\r\n]*\r?\n([\s\S]*?)\r?\n?\s*```\s*$/;

export function stripCodeFence(raw: string): string {
  const match = FENCED.exec(raw);
  return match?.[1] !== undefined ? match[1].trim() : raw;
}
