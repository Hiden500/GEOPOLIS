/**
 * Единый слой мутации GameState (docs/plans/03_MODIFIERS_COMMANDS.md,
 * MASTER_PROMPT.md правило 2). Команда — функция `(game, ...params) =>
 * CommandResult`; LLM-действия, роуты игрока и AiBehaviorTick вызывают одни
 * и те же команды вместо прямой мутации полей или разрозненных вызовов
 * сервисов. Расположение — `server/src/commands/`, не `shared/src/sim/
 * commands/` (буква правила 2): весь слой тиков сегодня физически живёт в
 * `server/src/simulation/`, не в `shared/src/sim/` (такой директории не
 * существует) — решение зафиксировано в docs/DECISIONS.md.
 */
export interface CommandResult<TApplied = void> {
  success: boolean;
  error?: string;
  /**
   * ФАКТИЧЕСКИ применённое изменение — то, что легло в состояние после клампов
   * и потолков, а не то, что просили. Команда — единственное место, где эта
   * разница видна: `memory.suppression` при 0.98 примет из запрошенных 0.41
   * ровно 0.02, и вызывающий обязан отчитываться этим числом, иначе движок
   * возвращает LLM выдуманную величину (docs/PRIMITIVES.md §4 — «после commit
   * движок возвращает LLM фактические величины… цифры правдивые»).
   *
   * Поле опционально: команды, у которых «сколько именно» не значит ничего
   * (создание сущности, установка флага), его не заполняют.
   */
  applied?: TApplied;
}
