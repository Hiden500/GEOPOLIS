/**
 * Подхватывает `server/.env` в СКРИПТАХ.
 *
 * ЗАЧЕМ. `process.loadEnvFile()` стоял только в `server/src/index.ts`, то есть
 * `.env` читал исключительно HTTP-сервер. Скрипты (`runCampaignWithLLM`,
 * `benchLocalModels`, `listLocalModels`) запускаются отдельным процессом и
 * переменных оттуда не видели вовсе: ключ, аккуратно вписанный в `server/.env`,
 * молча не доезжал до запроса, а эндпоинт с авторизацией отвечал 401 — и
 * выглядело это как «ключ неверный», хотя он просто не был прочитан.
 *
 * Путь резолвится от САМОГО модуля, а не от текущего каталога: скрипт,
 * запущенный из корня репозитория, иначе искал бы `.env` не там, где он лежит.
 *
 * Импортировать первой строкой — до модулей, читающих `process.env`.
 */
import { fileURLToPath } from "node:url";
import * as path from "node:path";

const envPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", ".env");

try {
  process.loadEnvFile(envPath);
} catch {
  // Файла нет — нормально: переменные могут приходить прямо из окружения, а
  // локальному рантайму без авторизации `.env` не нужен вообще.
}
