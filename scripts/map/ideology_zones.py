#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Координаты идеологии 1946 и обратное отображение «координаты -> именованная
зона» (docs/CONCEPT.md §4.2).

Один источник для двух генераторов, чтобы координаты и ярлык физически не могли
разъехаться:

    scripts/map/config/ideology_1946.json   — авторские координаты 157 стран
        |
        +-> generate_demographics_1946.py -> server/data/scenarios/1946/ideology.json
        +-> generate_country_registry.py  -> politics.ideology в countries.json

Оба генератора читают ОДИН файл-вход и никогда не читают выход друг друга —
поэтому цикла зависимостей нет, а ярлык перестаёт быть вторым авторским полем.

------------------------------------------------------------------------------
ЗОНЫ — ОБЛАСТИ, А НЕ ТОЧКИ (изменение модели, а не мелочь)
------------------------------------------------------------------------------
`IDEOLOGY_LABEL_COORDINATES` (shared/src/defines/discontent.ts) — таблица из
пяти ТОЧЕК. Для прямого хода (ярлык -> координаты, фолбэк неразмеченной страны)
точки достаточно: ярлыков пять, каждому нужна одна позиция.

Обратный ход так не работает. docs/CONCEPT.md §4.2 описывает зоны как
«именованные зоны (ОБЛАСТИ спектра)», и это именно тот случай, когда разница
существенна: стран 157, они рассыпаны по всему квадрату, и «ближайшая точка
каталога» даёт бессмыслицу. Замер по фактическим данным:

  - три якоря — Traditionalism (0.20,-0.45), Nationalism (0.10,-0.60) и
    Authoritarianism (0.00,-0.75) — почти коллинеарны и стоят в 0.18 друг от
    друга при разбросе данных ~2.0. По правилу ближайшей точки 25 стран
    получают ярлык с запасом < 0.025, то есть правка координаты на один шаг
    сетки (0.05) молча переворачивает ярлык;
  - центр спектра каталогом не покрыт вовсе: Аргентина, Мексика, Турция,
    Иран, оккупационные зоны Австрии лежат в 0.5..0.67 от ЛЮБОГО якоря, и
    «ближайший» для них — вопрос арифметики, а не смысла.

Поэтому обратное отображение — разбиение квадрата [-1,1]x[-1,1] на пять
областей границами, а не поиск ближайшего якоря. Границы взяты как СЕРЕДИНЫ
между якорями каталога по той оси, которая эти зоны разделяет: правило
остаётся привязанным к каталогу (а не подогнанным под текущие данные), и
каждый якорь по построению попадает в свою же зону — это свойство round-trip,
закреплённое тестом (test_validate_demographics_1946.py).

------------------------------------------------------------------------------
ЧЕГО ЭТО ПРАВИЛО НЕ УМЕЕТ (названо прямо)
------------------------------------------------------------------------------
Traditionalism / Nationalism / Authoritarianism не разделяются двумя осями
честно: это три РАЗНЫХ источника легитимности (традиция, нация, голая власть)
в одной и той же области спектра, а не три разные точки спектра. Каталог
различает их по экономической оси (0.20 / 0.10 / 0.00) — это отображение и
используется ниже как наименее плохое: на восьми рукописных ярлыках реестра
(единственная авторская истина, какая есть) оно даёт 5/8 против 2/8 у правила
ближайшей точки и 2/8 у разбиения по политической оси.

Остаток — не дефект данных, а бедность каталога: расхождения перечислены в
docs/IDEOLOGY_1946_PROVENANCE.md и являются материалом для отдельного решения
о расширении списка зон (docs/CONCEPT.md §4.2 упоминает «фашизм», которого в
каталоге нет вовсе).
"""
import json
from pathlib import Path

CONFIG_PATH = Path(__file__).resolve().parent / "config" / "ideology_1946.json"

# Каталог именованных зон. Обязан совпадать с IDEOLOGY_LABEL_COORDINATES
# (shared/src/defines/discontent.ts): там он читается как фолбэк ярлык ->
# координаты, здесь — как якоря обратного хода. Расхождение двух таблиц ловит
# validate_demographics_1946.py.
ZONE_ANCHORS: dict[str, tuple[float, float]] = {
    "Communism": (-0.90, -0.80),
    "Liberal Democracy": (0.35, 0.75),
    "Traditionalism": (0.20, -0.45),
    "Nationalism": (0.10, -0.60),
    "Authoritarianism": (0.00, -0.75),
}

# --- границы областей: середины между якорями по разделяющей оси ---

# Политическая: Liberal Democracy (+0.75) <-> ближайший авторитарный якорь
# Traditionalism (-0.45). Выше границы режим считается демократическим
# независимо от экономики — поэтому лейбористская Британия и Чехословакия
# Народного фронта остаются Liberal Democracy, будучи заметно левее США.
DEMOCRATIC_FLOOR = (0.75 + -0.45) / 2  # +0.15

# Экономическая: Communism (-0.90) <-> Authoritarianism (0.00).
COLLECTIVIST_CEILING = (-0.90 + 0.00) / 2  # -0.45

# Политическая: Communism (-0.80) <-> Traditionalism (-0.45). Вторая ось у
# коммунизма нужна, иначе левая экономика сама по себе делает «коммунизмом»
# любой послевоенный этатизм: Венгрия 1946 (-0.45, -0.30) — коалиция во главе
# с Партией мелких хозяев, а не однопартийный режим, и по экономической оси она
# ровно на границе.
COLLECTIVIST_POLITICAL_CEILING = (-0.80 + -0.45) / 2  # -0.625

# Экономическая: Traditionalism (0.20) <-> Nationalism (0.10).
TRADITIONALIST_FLOOR = (0.20 + 0.10) / 2  # +0.15

# Экономическая: Nationalism (0.10) <-> Authoritarianism (0.00).
NATIONALIST_FLOOR = (0.10 + 0.00) / 2  # +0.05


def zone_for(economic: float, political: float) -> str:
    """Именованная зона по координатам. Тотальна (любая точка квадрата даёт
    ярлык) и детерминирована; на границе ярлык достаётся более «правой» зоне.

    Порядок проверок — не косметика: политическая ось решает первой, потому что
    ярлык описывает ТИП РЕЖИМА, а экономическая ось у демократий разбросана от
    -0.55 (Чехословакия) до +0.55 (Швейцария) и типа режима не меняет.
    """
    if political >= DEMOCRATIC_FLOOR:
        return "Liberal Democracy"
    if economic <= COLLECTIVIST_CEILING and political <= COLLECTIVIST_POLITICAL_CEILING:
        return "Communism"
    if economic >= TRADITIONALIST_FLOOR:
        return "Traditionalism"
    if economic >= NATIONALIST_FLOOR:
        return "Nationalism"
    return "Authoritarianism"


def load_coordinates(path: Path | None = None) -> dict[str, tuple[float, float]]:
    """Авторские координаты из config/ideology_1946.json: country_id -> (e, p)."""
    payload = json.loads((path or CONFIG_PATH).read_text(encoding="utf-8"))
    return {
        entry["countryId"]: (entry["economic"], entry["political"])
        for entry in payload["countries"]
    }
