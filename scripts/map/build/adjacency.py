"""
adjacency.py — общие правила смежности полигонов для графов проекта.

Два правила, которые обязаны совпадать у всех строителей графов, иначе один
считает соседями то, что другой соседями не считает:

  real_touch  — что считается настоящей границей, а что геометрическим углом;
  seam_pairs  — смежность через линию перемены дат (±180°).

**Про шов.** Геометрия проекта плоская: долгота хранится как x, и для shapely
фигура на -179.99 отстоит от фигуры на +179.99 на 359.98° — то есть на весь
мир. Физически они соседи. Рабочий буфер (0.01° ≈ 1 км) такой разрыв не
перекрывает и никогда не перекроет: увеличить его до 360° значило бы соединить
всё со всем.

Приём: копия западной фигуры, сдвинутая на +360°, ложится вплотную к восточной,
и дальше работает обычная проверка пересечения. Сдвиг — только для проверки;
в выходную геометрию сдвинутые копии не попадают.

Почему до сегодняшнего дня этого не требовалось: каждая из шести фигур,
достигающих ±180 в водном слое (South Pacific, North Pacific, Southern, Arctic,
Bering Sea, Chukchi Sea), — ОДНА фича из двух-трёх частей, лежащих по обе
стороны шва. Ребро между разными фичами через шов не возникало потому, что
таких пар просто не было, а не потому, что код умел их находить. Любая нарезка
монолитов это положение ломает.
"""
from shapely.affinity import translate
from shapely.strtree import STRtree

# Пара, пересечение которой короче/меньше этого, касается в одной точке:
# геометрический "угол", а не граница. Величины исторические — ровно те, что
# стояли в `build_neighbor_graph.py` до выделения правила в общий модуль.
TOUCH_MIN_LENGTH = 1e-6
TOUCH_MIN_AREA = 1e-9

# Насколько близко к ±180 фигура должна подойти, чтобы попасть в кандидаты на
# шовную смежность. Это ОТБОР КАНДИДАТОВ, а не критерий смежности: смежность
# решает `real_touch` на настоящем пересечении. Величина с большим запасом
# против рабочего буфера — кандидатов единицы, экономить не на чем.
SEAM_REACH_DEG = 1.0

SEAM_SHIFT_DEG = 360.0


def real_touch(inter) -> bool:
    """Пересечение — настоящая граница, а не касание в точке."""
    if inter is None or inter.is_empty:
        return False
    return inter.length >= TOUCH_MIN_LENGTH or inter.area >= TOUCH_MIN_AREA


def near_seam(geom, reach_deg: float = SEAM_REACH_DEG) -> bool:
    minx, _, maxx, _ = geom.bounds
    return maxx >= 180.0 - reach_deg or minx <= -180.0 + reach_deg


def seam_pairs(geoms, reach_deg: float = SEAM_REACH_DEG):
    """Пары индексов `(i, j)`, смежные ЧЕРЕЗ ±180.

    `geoms` — те же геометрии, на которых строится основной граф (у вызывающих
    это буферизованные полигоны): правило касания обязано применяться к тому же
    входу, иначе шовные рёбра появлялись бы по другому критерию.

    Пара `(i, i)` не возвращается: фича из частей по обе стороны шва — одна
    фича, соседства с самой собой не бывает. Результат отсортирован, поэтому
    порядок рёбер не зависит от порядка обхода дерева.
    """
    cand = [i for i, g in enumerate(geoms) if near_seam(g, reach_deg)]
    if len(cand) < 2:
        return []

    shifted = [translate(geoms[i], xoff=SEAM_SHIFT_DEG) for i in cand]
    tree = STRtree(shifted)

    found = set()
    for i in cand:
        for k in tree.query(geoms[i]):
            k = int(k)
            j = cand[k]
            if j == i:
                continue
            if real_touch(geoms[i].intersection(shifted[k])):
                found.add((min(i, j), max(i, j)))
    return sorted(found)
